fn s(x: &str) -> String {
    let mut out = String::with_capacity(x.len() + 2);
    out.push('"');
    for ch in x.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn guill(x: &str) -> String {
    format!("«{x}»")
}

fn opt<T>(o: &Option<T>, f: impl FnOnce(&T) -> String) -> String {
    match o {
        Some(v) => format!("(some {})", f(v)),
        None => "none".into(),
    }
}

fn list<T>(xs: &[T], f: impl Fn(&T) -> String) -> String {
    format!("[{}]", xs.iter().map(f).collect::<Vec<_>>().join(", "))
}

fn vec_arr<T>(xs: &[T], f: impl Fn(&T) -> String) -> String {
    format!("#[{}]", xs.iter().map(f).collect::<Vec<_>>().join(", "))
}

fn sign(sg: Sign) -> &'static str {
    match sg { Sign::None => ".none", Sign::Plus => ".plus", Sign::Minus => ".minus" }
}

fn sub(sb: Sub) -> &'static str {
    match sb { Sub::None => ".none", Sub::F => ".f", Sub::Z => ".z" }
}

fn numeral(n: &Numeral) -> String {
    match n {
        Numeral::Dec(v) => format!("(.dec {v})"),
        Numeral::Hex(v, d) => format!("(.hex {v} {})", s(d)),
        Numeral::Frac(w, f, p) => format!("(.frac {w} {f} {p})"),
    }
}

fn mag(m: &Mag) -> String {
    match m {
        Mag::Num(n) => format!("(.num {})", numeral(n)),
        Mag::Inf => ".inf".into(),
    }
}

struct EmitCtx<'a> {
    ids: &'a Ids,
    vars: HashMap<&'a str, usize>,
    allow_anon_slots: bool,
}

impl<'a> EmitCtx<'a> {
    fn new(ids: &'a Ids, vars: HashMap<&'a str, usize>) -> Self {
        Self { ids, vars, allow_anon_slots: false }
    }
    fn header(ids: &'a Ids) -> Self {
        Self { ids, vars: HashMap::new(), allow_anon_slots: true }
    }
    fn var(&self, name: &str) -> Result<usize, String> {
        if let Some(&id) = self.vars.get(name) {
            return Ok(id);
        }
        if self.allow_anon_slots {
            if let Some(rest) = name.strip_prefix('v') {
                if let Ok(n) = rest.parse::<usize>() {
                    return Ok(n);
                }
            }
        }
        Err(format!("undeclared variable `{name}`"))
    }
    fn slot(&self, name: &str) -> Result<usize, String> {
        self.var(name)
    }
}

fn alg_id(ids: &Ids, a: &AlgRef) -> Result<String, String> {
    Ok(format!("⟨{}, {}⟩", ids.clause.get(&a.clause)?, a.idx))
}

fn prim_id(ids: &Ids, p: &str) -> Result<usize, String> {
    if p.is_empty() {
        Ok(100000)
    } else {
        ids.prim.get(p)
    }
}

fn val(cx: &EmitCtx, v: &ValLit) -> Result<String, String> {
    Ok(match v {
        ValLit::Undefined => ".undefined".into(),
        ValLit::Null => ".null".into(),
        ValLit::Bool(true) => ".true".into(),
        ValLit::Bool(false) => ".false".into(),
        ValLit::This => ".this".into(),
        ValLit::Str(x) => format!("(.str {})", s(x)),
        ValLit::Nan(sb) => format!("(.nan {})", sub(*sb)),
        ValLit::Num(sg, m, sb) => format!("(.num {} {} {})", sign(*sg), mag(m), sub(*sb)),
        ValLit::Err(f) => format!("(.err {})", cx.ids.field.get(f)?),
        ValLit::BigN(n) => format!("(.bigN {})", numeral(n)),
    })
}

fn expr(cx: &EmitCtx, e: &Expr) -> Result<String, String> {
    Ok(match e {
        Expr::Var(x) => format!("(.var {})", cx.var(x)?),
        Expr::Bnd(x) => format!("(.bnd {})", cx.var(x)?),
        Expr::Val(v) => format!("(.val {})", val(cx, v)?),
        Expr::Math(sg, m) => format!("(.math {} {})", sign(*sg), mag(m)),
        Expr::Enum(en) => format!("(.enum {})", cx.ids.enum_.get(en)?),
        Expr::Param(p) => format!("(.param {})", cx.ids.param.get(p)?),
        Expr::Intrinsic(f) => format!("(.intrinsic {})", cx.ids.field.get(f)?),
        Expr::FieldName(f) => format!("(.fieldName {})", cx.ids.field.get(f)?),
        Expr::Nt(n, args) => {
            let xs: Vec<_> = args
                .iter()
                .map(|a| Ok(format!("({}, {})", cx.ids.param.get(&a.param)?, a.plus)))
                .collect::<Result<_, String>>()?;
            format!("(.nt {} [{}])", cx.ids.nt.get(n)?, xs.join(", "))
        }
        Expr::Prod(ps) => {
            let xs: Vec<_> = ps.iter().map(|p| Ok(cx.ids.prod.get(p)?.to_string())).collect::<Result<_, String>>()?;
            format!("(.prod [{}])", xs.join(", "))
        }
        Expr::CodeUnit(n, d, nm) => format!("(.codeUnit {n} {} {})", s(d), opt(nm, |x| s(x))),
        Expr::CodePoint(n, d, nm) => format!("(.codePoint {n} {} {})", s(d), opt(nm, |x| s(x))),
        Expr::Code(x) => format!("(.code {})", s(x)),
        Expr::Term(x) => format!("(.term {})", s(x)),
        Expr::Call(Callee::Alg(a), args) => {
            let as_: Vec<_> = args.iter().map(|x| expr(cx, x)).collect::<Result<_, _>>()?;
            format!("(.call (.alg {}) [{}])", alg_id(cx.ids, a)?, as_.join(", "))
        }
        Expr::Call(Callee::Prim(p), args) => {
            let as_: Vec<_> = args.iter().map(|x| expr(cx, x)).collect::<Result<_, _>>()?;
            format!("(.call (.prim {}) [{}])", prim_id(cx.ids, p)?, as_.join(", "))
        }
        Expr::CallAt(a, args) => {
            let as_: Vec<_> = args.iter().map(|x| expr(cx, x)).collect::<Result<_, _>>()?;
            format!("(.callAt {} [{}])", alg_id(cx.ids, a)?, as_.join(", "))
        }
        Expr::Sdo(sd, sub, args) => {
            let as_: Vec<_> = args.iter().map(|x| expr(cx, x)).collect::<Result<_, _>>()?;
            format!("(.sdo {} {} [{}])", cx.ids.sdo.get(sd)?, expr(cx, sub)?, as_.join(", "))
        }
        Expr::Component(c, sub) => format!("(.component {} {})", cx.ids.field.get(c)?, expr(cx, sub)?),
        Expr::Field(o, f) => format!("(.field {} {})", expr(cx, o)?, cx.ids.field.get(f)?),
        Expr::IMethod(o, m, args) => {
            let as_: Vec<_> = args.iter().map(|x| expr(cx, x)).collect::<Result<_, _>>()?;
            format!("(.imethod {} {} [{}])", expr(cx, o)?, cx.ids.field.get(m)?, as_.join(", "))
        }
        Expr::CMethod(o, m, args) => {
            let as_: Vec<_> = args.iter().map(|x| expr(cx, x)).collect::<Result<_, _>>()?;
            format!("(.cmethod {} {} [{}])", expr(cx, o)?, cx.ids.method.get(m)?, as_.join(", "))
        }
        Expr::Apply(f, args) => {
            let as_: Vec<_> = args.iter().map(|x| expr(cx, x)).collect::<Result<_, _>>()?;
            format!("(.apply {} [{}])", expr(cx, f)?, as_.join(", "))
        }
        Expr::Index(o, i) => format!("(.index {} {})", expr(cx, o)?, expr(cx, i)?),
        Expr::Q(x) => format!("(.q {})", expr(cx, x)?),
        Expr::Bang(x) => format!("(.bang {})", expr(cx, x)?),
        Expr::Un(UnOp::Neg, x) => format!("(.un .neg {})", expr(cx, x)?),
        Expr::Un(UnOp::Not, x) => format!("(.un .not {})", expr(cx, x)?),
        Expr::Bin(op, a, b) => {
            let o = match op {
                BinOp::Add => ".add",
                BinOp::Sub => ".sub",
                BinOp::Plus => ".plus",
                BinOp::Mul => ".mul",
                BinOp::Div => ".div",
                BinOp::Modulo => ".modulo",
                BinOp::Times => ".times",
                BinOp::Pow => ".pow",
            };
            format!("(.bin {o} {} {})", expr(cx, a)?, expr(cx, b)?)
        }
        Expr::Paren(x) => format!("(.paren {})", expr(cx, x)?),
        Expr::List(es) => {
            let xs: Vec<_> = es.iter().map(|x| expr(cx, x)).collect::<Result<_, _>>()?;
            format!("(.list [{}])", xs.join(", "))
        }
        Expr::Record(sort, fs) => {
            let ks = match sort {
                Some(so) => format!("(some {})", cx.ids.sort.get(so)?),
                None => "none".into(),
            };
            let fstr: Vec<_> = fs
                .iter()
                .map(|(f, v)| Ok(format!("({}, {})", cx.ids.field.get(f)?, expr(cx, v)?)))
                .collect::<Result<_, String>>()?;
            format!("(.record {ks} [{}])", fstr.join(", "))
        }
        Expr::ResumedWith(x) => format!("(.resumedWith {})", expr(cx, x)?),
        Expr::ThisNode => ".thisNode".into(),
        Expr::Child(k, n) => format!("(.child {k} {})", cx.ids.nt.get(n)?),
        Expr::ChildOf(o, n) => format!("(.childOf {} {})", expr(cx, o)?, cx.ids.nt.get(n)?),
        Expr::ThisValue => ".thisValue".into(),
        Expr::NewTarget => ".newTarget".into(),
        Expr::Xref(c) => format!("(.xref {})", cx.ids.clause.get(c)?),
        Expr::Closure(k) => format!("(.closure {k})"),
        Expr::Table(t) => format!("(.table {})", cx.ids.table.get(t)?),
        Expr::Definition(c) => format!("(.definition {})", cx.ids.clause.get(c)?),
        Expr::TableStep(t, k) => format!("(.tableStep {} {})", cx.ids.table.get(t)?, expr(cx, k)?),
        Expr::Data(DataLit::Sort(so)) => format!("(.data (.sort {}))", cx.ids.sort.get(so)?),
        Expr::Data(DataLit::Choice(i)) => format!("(.data (.choice {i}))"),
        Expr::Data(DataLit::Absent) => "(.data .absent)".into(),
        Expr::OfCond(c) => format!("(.ofCond {})", cond(cx, c)?),
    })
}

fn conj_str(j: Conj) -> &'static str {
    match j { Conj::And => ".and", Conj::Or => ".or" }
}

fn pred(cx: &EmitCtx, p: &Pred) -> Result<String, String> {
    Ok(match p {
        Pred::IsVal { neg, neither, vals } => {
            let vs: Vec<_> = vals.iter().map(|v| expr(cx, v)).collect::<Result<_, _>>()?;
            format!("(.isVal {neg} {neither} [{}])", vs.join(", "))
        }
        Pred::IsTy { neg, neither, tys } => {
            let ts: Vec<_> = tys.iter().map(|t| ty(cx, t)).collect::<Result<_, _>>()?;
            format!("(.isTy {neg} {neither} [{}])", ts.join(", "))
        }
        Pred::Call { callee: Callee::Alg(a), args, neg } => {
            let xs: Vec<_> = args.iter().map(|x| expr(cx, x)).collect::<Result<_, _>>()?;
            format!("(.call (.alg {}) [{}] {neg})", alg_id(cx.ids, a)?, xs.join(", "))
        }
        Pred::Call { callee: Callee::Prim(pr), args, neg } => {
            let xs: Vec<_> = args.iter().map(|x| expr(cx, x)).collect::<Result<_, _>>()?;
            format!("(.call (.prim {}) [{}] {neg})", prim_id(cx.ids, pr)?, xs.join(", "))
        }
    })
}

fn preds(cx: &EmitCtx, rest: &[(Conj, Pred)]) -> Result<String, String> {
    let xs: Vec<_> = rest
        .iter()
        .map(|(j, p)| Ok(format!("({}, {})", conj_str(*j), pred(cx, p)?)))
        .collect::<Result<_, String>>()?;
    Ok(format!("[{}]", xs.join(", ")))
}

fn cond(cx: &EmitCtx, c: &Cond) -> Result<String, String> {
    Ok(match c {
        Cond::Preds(e, p, rest) => format!("(.preds {} {} {})", expr(cx, e)?, pred(cx, p)?, preds(cx, rest)?),
        Cond::Rel(op, a, b) => {
            let os = match op { RelOp::Lt => ".lt", RelOp::Le => ".le", RelOp::Gt => ".gt", RelOp::Ge => ".ge", RelOp::Eq => ".eq", RelOp::Ne => ".ne" };
            format!("(.rel {os} {} {})", expr(cx, a)?, expr(cx, b)?)
        }
        Cond::And(cs) => {
            let xs: Vec<_> = cs.iter().map(|x| cond(cx, x)).collect::<Result<_, _>>()?;
            format!("(.and [{}])", xs.join(", "))
        }
        Cond::Or(cs) => {
            let xs: Vec<_> = cs.iter().map(|x| cond(cx, x)).collect::<Result<_, _>>()?;
            format!("(.or [{}])", xs.join(", "))
        }
        Cond::Paren(x) => format!("(.paren {})", cond(cx, x)?),
        Cond::Alg(a) => format!("(.alg {})", alg_id(cx.ids, a)?),
        Cond::Expr(e) => format!("(.expr {})", expr(cx, e)?),
        Cond::Pass(k) => format!("(.pass {})", s(k)),
    })
}

fn ty(cx: &EmitCtx, t: &TyExpr) -> Result<String, String> {
    Ok(match t {
        TyExpr::Sort { mods, sort } => {
            let ms: Vec<_> = mods.iter().map(|m| Ok(cx.ids.sort.get(m)?.to_string())).collect::<Result<_, String>>()?;
            format!("(.sort [{}] {})", ms.join(", "), cx.ids.sort.get(sort)?)
        }
        TyExpr::ListOf(inner) => format!("(.listOf {})", ty(cx, inner)?),
        TyExpr::SeqOf(inner) => format!("(.seqOf {})", ty(cx, inner)?),
        TyExpr::ButNot(a, b) => format!("(.butNot {} {})", ty(cx, a)?, ty(cx, b)?),
        TyExpr::Doc(d) => format!("(.doc {})", s(d)),
        TyExpr::Union(ts) => {
            let xs: Vec<_> = ts.iter().map(|x| ty(cx, x)).collect::<Result<_, _>>()?;
            format!("(.union [{}])", xs.join(", "))
        }
        TyExpr::Completion(o) => match o {
            Some(inner) => format!("(.completion (some {}))", ty(cx, inner)?),
            None => "(.completion none)".into(),
        },
        TyExpr::Interval(base, lo, hi) => format!("(.interval {} {} {})", ty(cx, base)?, expr(cx, lo)?, expr(cx, hi)?),
        TyExpr::Value(e) => format!("(.value {})", expr(cx, e)?),
        TyExpr::Var(x) => format!("(.var {})", cx.var(x)?),
        TyExpr::Nt(n) => format!("(.nt {})", cx.ids.nt.get(n)?),
        TyExpr::Record(fs) => {
            let xs: Vec<_> = fs
                .iter()
                .map(|(f, v)| Ok(format!("({}, {})", cx.ids.field.get(f)?, ty(cx, v)?)))
                .collect::<Result<_, String>>()?;
            format!("(.record [{}])", xs.join(", "))
        }
        TyExpr::That(base, p, rest) => format!("(.that {} {} {})", ty(cx, base)?, pred(cx, p)?, preds(cx, rest)?),
        TyExpr::Pred(p) => format!("(.pred {})", pred(cx, p)?),
    })
}

fn body(cx: &EmitCtx, b: &Body) -> Result<String, String> {
    match b {
        Body::Inline(st) => Ok(format!("(.inline {})", stmt(cx, st)?)),
        Body::Block(ns) => Ok(format!("(.block {})", stmts(cx, ns)?)),
    }
}

fn arm(cx: &EmitCtx, a: &Arm) -> Result<String, String> {
    let mc = match &a.cond {
        Some(c) => format!("(some {})", cond(cx, c)?),
        None => "none".into(),
    };
    Ok(format!(".mk {mc} {}", body(cx, &a.body)?))
}

fn stmts(cx: &EmitCtx, ns: &[Stmt]) -> Result<String, String> {
    let xs: Vec<_> = ns.iter().map(|st| stmt(cx, st)).collect::<Result<_, _>>()?;
    Ok(format!("[{}]", xs.join(", ")))
}

fn stmt(cx: &EmitCtx, st: &Stmt) -> Result<String, String> {
    Ok(match st {
        Stmt::Let(x, e) => format!("(.let_ {} {})", cx.slot(x)?, expr(cx, e)?),
        Stmt::Set(Place::Var(x), e) => format!("(.set (.var {}) {})", cx.slot(x)?, expr(cx, e)?),
        Stmt::Set(Place::Field(o, f), e) => format!("(.set (.field {} {}) {})", expr(cx, o)?, cx.ids.field.get(f)?, expr(cx, e)?),
        Stmt::Set(Place::Expr(lhs), e) => format!("(.set (.expr {}) {})", expr(cx, lhs)?, expr(cx, e)?),
        Stmt::Ret(oe) => match oe { Some(e) => format!("(.ret (some {}))", expr(cx, e)?), None => "(.ret none)".into() },
        Stmt::Perform(e) => format!("(.perform {})", expr(cx, e)?),
        Stmt::If(c, bd, arms, els) => {
            let as_: Vec<_> = arms.iter().map(|a| Ok(format!("({})", arm(cx, a)?))).collect::<Result<_, String>>()?;
            let el = match els { Some(a) => format!("(some ({}))", arm(cx, a)?), None => "none".into() };
            format!("(.if_ {} {} [{}] {el})", cond(cx, c)?, body(cx, bd)?, as_.join(", "))
        }
        Stmt::IfElse(c, s1, s2) => format!("(.ifElse {} {} {})", cond(cx, c)?, stmt(cx, s1)?, stmt(cx, s2)?),
        Stmt::Assert(c) => format!("(.assert {})", cond(cx, c)?),
        Stmt::AssertAlways(c) => format!("(.assertAlways {})", cond(cx, c)?),
        Stmt::AssertIf(c, d) => format!("(.assertIf {} {})", cond(cx, c)?, cond(cx, d)?),
        Stmt::Unreachable(v) => format!("(.unreachable {v})"),
        Stmt::ThrowVal(e) => format!("(.throwVal {})", expr(cx, e)?),
        Stmt::Note(t) => format!("(.note {})", s(t)),
        Stmt::Repeat(ns) => format!("(.repeat_ {})", stmts(cx, ns)?),
        Stmt::RepeatWhile(c, ns) => format!("(.repeatWhile {} {})", cond(cx, c)?, stmts(cx, ns)?),
        Stmt::RepeatUntil(c, ns) => format!("(.repeatUntil {} {})", cond(cx, c)?, stmts(cx, ns)?),
        Stmt::ForEach { x, ty: t, list: l, rev, body: bd } => {
            let ts = match t { Some(tv) => format!("(some {})", ty(cx, tv)?), None => "none".into() };
            format!("(.forEach {} {ts} {} {rev} {})", cx.slot(x)?, expr(cx, l)?, body(cx, bd)?)
        }
        Stmt::ForEachRec { fields, x, list: l, body: bd } => {
            let fs: Vec<_> = fields.iter().map(|f| Ok(cx.ids.field.get(f)?.to_string())).collect::<Result<_, String>>()?;
            format!("(.forEachRec [{}] {} {} {})", fs.join(", "), cx.slot(x)?, expr(cx, l)?, body(cx, bd)?)
        }
        Stmt::ForRange { x, lo, lo_incl, hi, hi_incl, desc, body: bd } => {
            format!("(.forRange {} {} {lo_incl} {} {hi_incl} {desc} {})", cx.slot(x)?, expr(cx, lo)?, expr(cx, hi)?, body(cx, bd)?)
        }
        Stmt::ForKeys { x, obj, cond: c, order, body: bd } => {
            format!("(.forKeys {} {} {} {order} {})", cx.slot(x)?, expr(cx, obj)?, cond(cx, c)?, body(cx, bd)?)
        }
        Stmt::ForIndex { x, list: l, body: bd } => format!("(.forIndex {} {} {})", cx.slot(x)?, expr(cx, l)?, body(cx, bd)?),
        Stmt::ForChildren { x, body: bd } => format!("(.forChildren {} {})", cx.slot(x)?, body(cx, bd)?),
        Stmt::ForChildrenOf { x, expr: e, body: bd } => format!("(.forChildrenOf {} {} {})", cx.slot(x)?, expr(cx, e)?, body(cx, bd)?),
        Stmt::RepeatN(e, ns) => format!("(.repeatN {} {})", expr(cx, e)?, stmts(cx, ns)?),
        Stmt::Suspend(e, v) => format!("(.suspend {} {v})", expr(cx, e)?),
        Stmt::Push(e, v) => format!("(.push {} {v})", expr(cx, e)?),
        Stmt::Remove(e, v) => format!("(.remove {} {v})", expr(cx, e)?),
        Stmt::RemoveRestore(e, r) => format!("(.removeRestore {} {})", expr(cx, e)?, expr(cx, r)?),
        Stmt::ResumeTop => ".resumeTop".into(),
        Stmt::ResumeLet { ctx, val, x } => format!("(.resumeLet {} {} {})", expr(cx, ctx)?, expr(cx, val)?, cx.slot(x)?),
        Stmt::Resume(e, v) => format!("(.resume {} {})", expr(cx, e)?, expr(cx, v)?),
        Stmt::SetCodeState(e, f) => format!("(.setCodeState {} {})", expr(cx, e)?, expr(cx, f)?),
        Stmt::Block(ns) => format!("(.block {})", stmts(cx, ns)?),
    })
}

fn alg_kind(k: AlgKind) -> &'static str {
    match k {
        AlgKind::Ao => ".ao",
        AlgKind::Sdo => ".sdo",
        AlgKind::Builtin => ".builtin",
        AlgKind::InternalMethod => ".internalMethod",
        AlgKind::ConcreteMethod => ".concreteMethod",
        AlgKind::NumericMethod => ".numericMethod",
        AlgKind::HostDefined => ".hostDefined",
        AlgKind::ImplDefined => ".implDefined",
        AlgKind::Untyped => ".untyped",
    }
}

fn closures(cx: &EmitCtx, cs: &[CloLit]) -> Result<String, String> {
    let mut xs = Vec::with_capacity(cs.len());
    for c in cs {
        let k = match c.kind {
            CloKind::Abstract => ".abstract",
            CloKind::Job => ".job",
            CloKind::Matcher => ".matcher",
            CloKind::MatcherContinuation => ".matcherContinuation",
            CloKind::ReadModifyWrite => ".readModifyWrite",
        };
        let ps = match &c.params {
            None => "none".into(),
            Some(v) => {
                let ns: Vec<_> = v.iter().map(|x| Ok(cx.slot(x)?.to_string())).collect::<Result<_, String>>()?;
                format!("(some [{}])", ns.join(", "))
            }
        };
        let caps: Vec<_> = c.captures.iter().map(|x| Ok(cx.slot(x)?.to_string())).collect::<Result<_, String>>()?;
        let fr = match &c.frame {
            None => String::new(),
            Some((a, b, d)) => format!(", frame := some ({}, {}, {})", cx.slot(a)?, cx.slot(b)?, cx.slot(d)?),
        };
        xs.push(format!("{{ kind := {k}, atomic := {}, params := {ps}, caps := [{}], body := {}{fr} }}", c.atomic, caps.join(", "), stmts(cx, &c.body)?));
    }
    Ok(format!("#[{}]", xs.join(",\n    ")))
}

fn make_vars<'a>(xs: &'a [String]) -> HashMap<&'a str, usize> {
    xs.iter().enumerate().map(|(i, n)| (n.as_str(), i)).collect()
}

fn wrap_mod(imports: &[&str], ns: &str, body: &str) -> String {
    let mut o = String::from("module\n\n");
    for imp in imports {
        writeln!(o, "public import {imp}").unwrap();
    }
    writeln!(o, "\n/-! {HEADER} -/\n\n@[expose] public section\n\nnamespace {ns}\n\nopen Ecma\n\n{body}\nend {ns}").unwrap();
    o
}

fn count_steps(ns: &[Stmt]) -> usize {
    ns.iter()
        .map(|s| {
            1 + match s {
                Stmt::If(_, bd, arms, els) => {
                    let bd_n = |b: &Body| if let Body::Block(xs) = b { count_steps(xs) } else { 0 };
                    bd_n(bd) + arms.iter().chain(els.iter()).map(|a| 1 + bd_n(&a.body)).sum::<usize>()
                }
                Stmt::Repeat(xs) | Stmt::RepeatWhile(_, xs) | Stmt::RepeatUntil(_, xs) | Stmt::RepeatN(_, xs) | Stmt::Block(xs) => count_steps(xs),
                Stmt::ForEach { body: Body::Block(xs), .. }
                | Stmt::ForEachRec { body: Body::Block(xs), .. }
                | Stmt::ForRange { body: Body::Block(xs), .. }
                | Stmt::ForKeys { body: Body::Block(xs), .. }
                | Stmt::ForIndex { body: Body::Block(xs), .. }
                | Stmt::ForChildren { body: Body::Block(xs), .. }
                | Stmt::ForChildrenOf { body: Body::Block(xs), .. } => count_steps(xs),
                _ => 0,
            }
        })
        .sum()
}

pub fn emit(spec: &Spec, ids: &Ids, out_dir: &Path) -> Result<(), String> {
    let mut files: BTreeMap<String, String> = BTreeMap::new();

    // Collect Decls, EarlyRows, Tables, Realm, and clause algorithms/rows.
    let mut ops_map = vec![String::new(); ids.clause.names.len()];
    let mut prim_docs = vec![(String::new(), String::new()); ids.prim.names.len()];
    let mut sort_defs: Vec<Option<SortDef>> = vec![None; ids.sort.names.len()];
    let mut sdo_headers: Vec<Option<SdoHeader>> = vec![None; ids.sdo.names.len()];
    let mut sdo_defaults: Vec<Option<AlgRef>> = vec![None; ids.sdo.names.len()];
    let mut checked_jobs: Vec<String> = Vec::new();
    let mut sort_aliases: Vec<(String, String)> = Vec::new();
    let mut gram_alts: Vec<(String, Vec<GrammarAltItem>)> = Vec::new();
    let mut clause_prods: Vec<(String, Vec<String>)> = Vec::new();

    let mut early_rows: Vec<&EarlyRow> = Vec::new();
    let mut tables: Vec<&TableDef> = Vec::new();
    let mut realm_symbols: Vec<String> = Vec::new();
    let mut realm_objs: Vec<&RObj> = Vec::new();
    let mut realm_clause_props: Vec<&ClauseProps> = Vec::new();

    // Group clause items by file stem (`clauses/S10.spectec` -> `S10` -> sharded into `S10_part1`, ...).
    enum ClauseItem<'a> {
        Def(&'a AlgDef),
        Row(&'a SdoRowDef),
    }
    let mut by_mod: BTreeMap<String, Vec<ClauseItem>> = BTreeMap::new();

    for f in &spec.files {
        let stem = Path::new(&f.rel_path)
            .file_stem()
            .and_then(|x| x.to_str())
            .unwrap_or("Other")
            .to_string();
        for item in &f.items {
            match item {
                TopItem::Decl(d) => match d {
                    Decl::Clause { id, op } => {
                        let cid = ids.clause.get(id)?;
                        if let Some(o) = op {
                            ops_map[cid] = o.clone();
                        }
                    }
                    Decl::ExternDef { name, sig, meaning } => {
                        let pid = ids.prim.get(name)?;
                        prim_docs[pid] = (sig.clone().unwrap_or_default(), meaning.clone().unwrap_or_default());
                    }
                    Decl::Syntax { name, def } => {
                        let sid = ids.sort.get(name)?;
                        sort_defs[sid] = def.clone();
                    }
                    Decl::Sdo { name, header, default } => {
                        let sid = ids.sdo.get(name)?;
                        sdo_headers[sid] = header.clone();
                        sdo_defaults[sid] = default.clone();
                    }
                    Decl::CheckedJobs(cs) => checked_jobs = cs.clone(),
                    Decl::SortAlias { from, to } => sort_aliases.push((from.clone(), to.clone())),
                    Decl::GrammarAlt { nt, items } => gram_alts.push((nt.clone(), items.clone())),
                    Decl::ClauseProds { clause, prods } => clause_prods.push((clause.clone(), prods.clone())),
                    Decl::Field(_) | Decl::Enum(_) | Decl::Method(_) => {}
                },
                TopItem::Early(e) => early_rows.push(e),
                TopItem::Table(t) => tables.push(t),
                TopItem::Symbols(syms) => realm_symbols = syms.clone(),
                TopItem::RObj(o) => realm_objs.push(o),
                TopItem::ClauseProps(cp) => realm_clause_props.push(cp),
                TopItem::Def(a) => by_mod.entry(stem.clone()).or_default().push(ClauseItem::Def(a)),
                TopItem::SdoRow(r) => by_mod.entry(stem.clone()).or_default().push(ClauseItem::Row(r)),
                _ => {}
            }
        }
    }

    // 1. Decls.lean
    {
        let mut o = String::new();
        writeln!(o, "def clauses : Array String := {}", vec_arr(&ids.clause.names, |x| s(x))).unwrap();
        writeln!(o, "\ndef ops : Array String := {}", vec_arr(&ops_map, |x| s(x))).unwrap();
        writeln!(o, "\ndef fields : Array String := {}", vec_arr(&ids.field.names, |x| s(x))).unwrap();
        writeln!(o, "\ndef enums : Array String := {}", vec_arr(&ids.enum_.names, |x| s(x))).unwrap();
        writeln!(o, "\ndef sdos : Array String := {}", vec_arr(&ids.sdo.names, |x| s(x))).unwrap();
        writeln!(o, "\ndef methods : Array String := {}", vec_arr(&ids.method.names, |x| s(x))).unwrap();
        writeln!(o, "\ndef nts : Array String := {}", vec_arr(&ids.nt.names, |x| s(x))).unwrap();
        writeln!(o, "\ndef params : Array String := {}", vec_arr(&ids.param.names, |x| s(x))).unwrap();
        writeln!(o, "\ndef prods : Array String := {}", vec_arr(&ids.prod.names, |x| s(x))).unwrap();
        writeln!(o, "\ndef prims : Array String := {}", vec_arr(&ids.prim.names, |x| s(x))).unwrap();
        writeln!(o, "\ndef primDocs : Array PrimDoc := {}", vec_arr(&prim_docs, |(sg, mn)| format!("{{ sig := {}, meaning := {} }}", s(sg), s(mn)))).unwrap();
        writeln!(o, "\ndef sorts : Array String := {}", vec_arr(&ids.sort.names, |x| s(x))).unwrap();

        let empty_cx = EmitCtx::header(ids);
        let sd_lean = |os: &Option<SortDef>| -> Result<String, String> {
            match os {
                None => Ok("none".into()),
                Some(sd) => {
                    let su: Vec<_> = sd.super_sorts.iter().map(|x| Ok(ids.sort.get(x)?.to_string())).collect::<Result<_, String>>()?;
                    let tst = match &sd.test {
                        SortTest::None => ".none".into(),
                        SortTest::Alg(a) => format!("(.alg {})", alg_id(ids, a)?),
                        SortTest::Prim { name, args, neg } => {
                            let as_: Vec<_> = args
                                .iter()
                                .map(|a| match a {
                                    SortTestArg::Subject => Ok(".subject".into()),
                                    SortTestArg::Enum(e) => Ok(format!("(.enum {})", ids.enum_.get(e)?)),
                                })
                                .collect::<Result<_, String>>()?;
                            format!("(.prim {} [{}] {neg})", prim_id(ids, name)?, as_.join(", "))
                        }
                    };
                    Ok(format!("(some {{ super := [{}], test := {tst}, record := {} }})", su.join(", "), sd.record))
                }
            }
        };
        let sds: Vec<_> = sort_defs.iter().map(sd_lean).collect::<Result<_, _>>()?;
        writeln!(o, "\ndef sortDefs : Array (Option SortDef) := #[{}]", sds.join(", ")).unwrap();

        let sh_lean = |oh: &Option<SdoHeader>| -> Result<String, String> {
            match oh {
                None => Ok("none".into()),
                Some(h) => {
                    let ps: Vec<_> = h
                        .params
                        .iter()
                        .map(|p| {
                            let to = match &p.ty { Some(t) => format!("(some {})", ty(&empty_cx, t)?), None => "none".into() };
                            Ok(format!("{{ x := {}, ty := {to}, optional := {}, rest := {} }}", p.slot, p.optional, p.rest))
                        })
                        .collect::<Result<_, String>>()?;
                    let ret = match &h.ret { Some(t) => format!("(some {})", ty(&empty_cx, t)?), None => "none".into() };
                    let recv = match &h.recv { Some((sl, t)) => format!("(some ({sl}, {}))", ty(&empty_cx, t)?), None => "none".into() };
                    Ok(format!("(some {{ kind := {}, params := [{}], ret := {ret}, recv := {recv} }})", alg_kind(h.kind), ps.join(", ")))
                }
            }
        };
        let shs: Vec<_> = sdo_headers.iter().map(sh_lean).collect::<Result<_, _>>()?;
        writeln!(o, "\ndef sdoHeaders : Array (Option Header) := #[{}]", shs.join(", ")).unwrap();

        let defs: Vec<_> = sdo_defaults
            .iter()
            .map(|oa| match oa { Some(a) => Ok(format!("(some {})", alg_id(ids, a)?)), None => Ok("none".into()) })
            .collect::<Result<_, String>>()?;
        writeln!(o, "\ndef sdoDefaults : Array (Option AlgId) := #[{}]", defs.join(", ")).unwrap();

        let cj: Vec<_> = checked_jobs.iter().map(|c| Ok(ids.clause.get(c)?.to_string())).collect::<Result<_, String>>()?;
        writeln!(o, "\ndef checkedJobs : Array ClauseId := #[{}]", cj.join(", ")).unwrap();

        let ga: Vec<_> = gram_alts
            .iter()
            .map(|(nt, items)| {
                let ts: Vec<_> = items
                    .iter()
                    .map(|i| match i {
                        GrammarAltItem::Text(x) => format!("(.text {})", s(x)),
                        GrammarAltItem::Cp(n) => format!("(.cp {})", s(n)),
                    })
                    .collect();
                Ok(format!("({}, [{}])", ids.nt.get(nt)?, ts.join(", ")))
            })
            .collect::<Result<_, String>>()?;
        writeln!(o, "\ndef alts : Array (NtId × List GTerminal) := #[{}]", ga.join(",\n    ")).unwrap();

        let cp: Vec<_> = clause_prods
            .iter()
            .map(|(c, ps)| {
                let xs: Vec<_> = ps.iter().map(|p| Ok(ids.prod.get(p)?.to_string())).collect::<Result<_, String>>()?;
                Ok(format!("({}, [{}])", ids.clause.get(c)?, xs.join(", ")))
            })
            .collect::<Result<_, String>>()?;
        writeln!(o, "\ndef clauseProds : Array (ClauseId × List ProdId) := #[{}]", cp.join(",\n    ")).unwrap();

        writeln!(
            o,
            "\ndef decls : Decls := {{\n  clauses, ops, fields, enums, sdos, methods, nts, params, prods, prims, primDocs,\n  sorts, sortDefs, sdoHeaders, sdoDefaults, checkedJobs, alts, clauseProds\n}}"
        )
        .unwrap();
        files.insert("Decls".into(), wrap_mod(&["Ecma.Notation.Syntax"], "Ecma.Gen", &o));
    }

    // 2. Clause shards (S*.lean / Helpers*.lean) & Index.lean
    let mut alg_mods = Vec::new();
    let mut row_mods = Vec::new();
    let mut chap_entries = Vec::new();
    let mut all_idx_imports = vec!["Ecma.Notation.Syntax".to_string()];

    for (stem, items) in &by_mod {
        let mut shards: Vec<(String, Vec<&ClauseItem>)> = Vec::new();
        let mut cur = Vec::new();
        let mut steps = 0usize;
        for it in items {
            let st_n = match it {
                ClauseItem::Def(a) => count_steps(&a.body) + a.closures.iter().map(|c| count_steps(&c.body)).sum::<usize>(),
                ClauseItem::Row(r) => count_steps(&r.steps) + r.closures.iter().map(|c| count_steps(&c.body)).sum::<usize>(),
            };
            if steps + st_n > SHARD_STEPS && !cur.is_empty() {
                shards.push((String::new(), cur));
                cur = Vec::new();
                steps = 0;
            }
            steps += st_n;
            cur.push(it);
        }
        if !cur.is_empty() {
            shards.push((String::new(), cur));
        }
        let multi = shards.len() > 1;
        for (i, (mname, _)) in shards.iter_mut().enumerate() {
            *mname = if multi { format!("{stem}_part{}", i + 1) } else { stem.clone() };
        }

        let mut chap_alg_mods = Vec::new();
        let mut chap_row_mods = Vec::new();
        for (mname, slice) in shards {
            all_idx_imports.push(format!("Ecma.Gen.{mname}"));
            let mut body = String::new();
            let mut algs_names = Vec::new();
            let mut rows_names = Vec::new();
            let mut used_names: BTreeSet<String> = ["algs".to_string(), "rows".to_string()].into_iter().collect();
            let mut counts: BTreeMap<String, usize> = BTreeMap::new();

            for it in slice {
                match it {
                    ClauseItem::Def(a) => {
                        let base = if a.name.is_empty() { a.id.clause.clone() } else { a.name.clone() };
                        let cnt = counts.entry(base.clone()).or_default();
                        let def_id = loop {
                            *cnt += 1;
                            let cand = if *cnt > 1 { format!("{base}.{}", *cnt) } else { base.clone() };
                            if used_names.insert(cand.clone()) {
                                break cand;
                            }
                        };
                        let g = guill(&def_id);
                        let cx = EmitCtx::new(ids, make_vars(&a.vars));

                        let ps: Vec<_> = a
                            .header
                            .params
                            .iter()
                            .map(|p| {
                                let to = match &p.ty { Some(t) => format!("(some {})", ty(&cx, t)?), None => "none".into() };
                                Ok(format!("{{ x := {}, ty := {to}, optional := {}, rest := {} }}", cx.slot(&p.x)?, p.optional, p.rest))
                            })
                            .collect::<Result<_, String>>()?;
                        let ret = match &a.header.ret { Some(t) => format!("(some {})", ty(&cx, t)?), None => "none".into() };
                        let recv = match &a.header.recv { Some((x, t)) => format!("(some ({}, {}))", cx.slot(x)?, ty(&cx, t)?), None => "none".into() };
                        let hdr = format!("{{ kind := {}, params := [{}], ret := {ret}, recv := {recv} }}", alg_kind(a.header.kind), ps.join(", "));
                        writeln!(
                            body,
                            "def {g} : Alg := {{\n  id := {}\n  name := {}\n  header := {hdr}\n  vars := {}\n  body := {}\n  closures := {} }}\n",
                            alg_id(ids, &a.id)?,
                            s(&a.name),
                            vec_arr(&a.vars, |v| s(v)),
                            stmts(&cx, &a.body)?,
                            closures(&cx, &a.closures)?
                        )
                        .unwrap();
                        algs_names.push(g);
                    }
                    ClauseItem::Row(r) => {
                        let cnt = counts.entry(r.sdo.clone()).or_default();
                        let def_id = loop {
                            *cnt += 1;
                            let cand = format!("{}.{}", r.sdo, *cnt);
                            if used_names.insert(cand.clone()) {
                                break cand;
                            }
                        };
                        let g = guill(&def_id);
                        let cx = EmitCtx::new(ids, make_vars(&r.vars));
                        let ps: Vec<_> = r.prods.iter().map(|p| Ok(ids.prod.get(p)?.to_string())).collect::<Result<_, String>>()?;
                        let form = match r.form { RowForm::Alg => ".alg", RowForm::Equation => ".equation" };
                        writeln!(
                            body,
                            "def {g} : SdoRow := {{\n  id := {}\n  sdo := {}\n  prods := [{}]\n  keys := {}\n  form := {form}\n  vars := {}\n  body := {}\n  closures := {}{} }}\n",
                            alg_id(ids, &r.id)?,
                            ids.sdo.get(&r.sdo)?,
                            ps.join(", "),
                            list(&r.keys, |k| s(k)),
                            vec_arr(&r.vars, |v| s(v)),
                            stmts(&cx, &r.steps)?,
                            closures(&cx, &r.closures)?,
                            if r.annex { "\n  annex := true" } else { "" }
                        )
                        .unwrap();
                        rows_names.push(g);
                    }
                }
            }
            writeln!(body, "def algs : List Alg := [{}]\n", algs_names.join(", ")).unwrap();
            writeln!(body, "def rows : List SdoRow := [{}]", rows_names.join(", ")).unwrap();
            if !algs_names.is_empty() {
                let m = format!("{mname}.algs");
                chap_alg_mods.push(m.clone());
                alg_mods.push(m);
            }
            if !rows_names.is_empty() {
                let m = format!("{mname}.rows");
                chap_row_mods.push(m.clone());
                row_mods.push(m);
            }
            files.insert(mname.clone(), wrap_mod(&["Ecma.Notation.Syntax"], &format!("Ecma.Gen.{mname}"), &body));
        }
        chap_entries.push(format!(
            "({}, ([{}] : List (List Alg)).flatten, ([{}] : List (List SdoRow)).flatten)",
            s(stem),
            chap_alg_mods.join(", "),
            chap_row_mods.join(", ")
        ));
    }

    {
        let idx_body = format!(
            "def algs : List (List Alg) := [\n  {}]\n\ndef rows : List (List SdoRow) := [\n  {}]\n\ndef chapters : List (String × List Alg × List SdoRow) := [\n  {}]",
            alg_mods.join(",\n  "),
            row_mods.join(",\n  "),
            chap_entries.join(",\n  ")
        );
        let imps: Vec<&str> = all_idx_imports.iter().map(|x| x.as_str()).collect();
        files.insert("Index".into(), wrap_mod(&imps, "Ecma.Gen", &idx_body));
    }

    // 3. Early*.lean
    {
        let mut shard_names = Vec::new();
        for (si, chunk) in early_rows.chunks(EARLY_SHARD_ROWS).enumerate() {
            let mname = format!("Early{}", si + 1);
            let mut body = String::new();
            let mut names = Vec::new();
            for (ri, r) in chunk.iter().enumerate() {
                let dname = guill(&format!("{}.{}", r.id.clause, r.id.idx));
                let cx = EmitCtx::new(ids, make_vars(&r.vars));
                let ps: Vec<_> = r.prods.iter().map(|p| Ok(ids.prod.get(p)?.to_string())).collect::<Result<_, String>>()?;
                fn emit_sent(cx: &EmitCtx, es: &EarlySent) -> Result<String, String> {
                    Ok(match es {
                        EarlySent::SyntaxError { early, cond: c, unless } => {
                            let u = match unless {
                                None => "none".into(),
                                Some((uf, d)) => {
                                    let ufs = match uf { UnlessForm::Plain => ".plain", UnlessForm::Comma => ".comma", UnlessForm::Optional => ".optional" };
                                    format!("(some ({ufs}, {}))", cond(cx, d)?)
                                }
                            };
                            format!("(.syntaxError {early} {} {u})", cond(cx, c)?)
                        }
                        EarlySent::SyntaxErrorIns(a, b) => format!("(.syntaxErrorIns {} {})", cond(cx, a)?, cond(cx, b)?),
                        EarlySent::MustCover(e, t) => format!("(.mustCover {} {})", expr(cx, e)?, ty(cx, t)?),
                        EarlySent::RulesApplied(ps, raw) => {
                            let xs: Vec<_> = ps.iter().map(|p| Ok(cx.ids.prod.get(p)?.to_string())).collect::<Result<_, String>>()?;
                            format!("(.rulesApplied [{}] {})", xs.join(", "), s(raw))
                        }
                        EarlySent::IfInline(c, inner) => format!("(.ifInline {} {})", cond(cx, c)?, emit_sent(cx, inner)?),
                        EarlySent::Info(st) => format!("(.info {})", stmt(cx, st)?),
                        EarlySent::NotApplied(c, st) => format!("(.notApplied {} {})", cond(cx, c)?, stmt(cx, st)?),
                        EarlySent::ForEachIn { x, ty: t, list: l, cond: c, stmt: st } => {
                            format!("(.forEachIn {} {} {} {} {})", cx.slot(x)?, ty(cx, t)?, expr(cx, l)?, cond(cx, c)?, stmt(cx, st)?)
                        }
                        EarlySent::Stmt(st) => format!("(.stmt {})", stmt(cx, st)?),
                    })
                }
                let sents: Vec<_> = r.sentences.iter().map(|x| emit_sent(&cx, x)).collect::<Result<_, _>>()?;
                // Ensure uniqueness within module
                let uname = if names.contains(&dname) { guill(&format!("{}.{}.{ri}", r.id.clause, r.id.idx)) } else { dname };
                let m = if r.modifies { "\n  modifies := true" } else { "" };
                writeln!(
                    body,
                    "def {uname} : EarlyRow := {{\n  id := {}\n  sdo := {}\n  prods := [{}]\n  keys := {}\n  vars := {}\n  body := [{}]{m} }}\n",
                    alg_id(ids, &r.id)?,
                    ids.sdo.get(&r.sdo)?,
                    ps.join(", "),
                    list(&r.keys, |k| s(k)),
                    vec_arr(&r.vars, |v| s(v)),
                    sents.join(", ")
                )
                .unwrap();
                names.push(uname);
            }
            writeln!(body, "def rows : List EarlyRow := [{}]", names.join(", ")).unwrap();
            files.insert(mname.clone(), wrap_mod(&["Ecma.Notation.Early"], &format!("Ecma.Gen.{mname}"), &body));
            shard_names.push(mname);
        }
        let imps: Vec<String> = shard_names.iter().map(|m| format!("Ecma.Gen.{m}")).collect();
        let imp_refs: Vec<&str> = imps.iter().map(|x| x.as_str()).collect();
        let lists: Vec<_> = shard_names.iter().map(|m| format!("{m}.rows")).collect();
        let body = format!("def earlyRows : List (List EarlyRow) := [{}]", lists.join(", "));
        files.insert("Early".into(), wrap_mod(&imp_refs, "Ecma.Gen", &body));
    }

    // 4. Tables*.lean
    {
        let mut by_id: Vec<Option<&TableDef>> = vec![None; ids.table.names.len()];
        for t in &tables {
            let tid = ids.table.get(&t.name)?;
            by_id[tid] = Some(t);
        }
        let mut shard_names = Vec::new();
        for (si, chunk) in by_id.chunks(TABLE_SHARD_COUNT).enumerate() {
            let mname = format!("Tables_{}", si + 1);
            let mut body = String::new();
            let mut names = Vec::new();
            for (offset, ot) in chunk.iter().enumerate() {
                let tid = si * TABLE_SHARD_COUNT + offset;
                let tname = &ids.table.names[tid];
                let dname = guill(tname);
                match ot.and_then(|t| t.body.as_ref().map(|b| (t, b))) {
                    None => {
                        writeln!(body, "def {dname} : Table := Table.retired\n").unwrap();
                    }
                    Some((_, tb)) => {
                        let cx = EmitCtx::new(ids, make_vars(&tb.vars));
                        let kind = match tb.kind {
                            TableKind::Fields => ".fields",
                            TableKind::Slots => ".slots",
                            TableKind::InternalMethods => ".internalMethods",
                            TableKind::AbstractMethods => ".abstractMethods",
                            TableKind::Components => ".components",
                            TableKind::Properties => ".properties",
                            TableKind::Intrinsics => ".intrinsics",
                            TableKind::Conversion => ".conversion",
                            TableKind::Data => ".data",
                        };
                        fn emit_tty(cx: &EmitCtx, tt: &TTy) -> Result<String, String> {
                            match tt {
                                TTy::Ty(t) => Ok(format!("(.ty {})", ty(cx, t)?)),
                                TTy::Records(fs) => {
                                    let xs: Vec<_> = fs.iter().map(|(f, t)| Ok(format!("({}, {})", cx.ids.field.get(f)?, ty(cx, t)?))).collect::<Result<_, String>>()?;
                                    Ok(format!("(.records [{}])", xs.join(", ")))
                                }
                            }
                        }
                        fn emit_cell_body(cx: &EmitCtx, cb: &CellBody) -> Result<String, String> {
                            Ok(match cb {
                                CellBody::Field(f) => format!("(.field {})", cx.ids.field.get(f)?),
                                CellBody::Ty(t) => format!("(.ty {})", emit_tty(cx, t)?),
                                CellBody::Sig(g) => {
                                    let nm = match g.kind {
                                        SigKind::Field => format!("(.internal {})", cx.ids.field.get(&g.name)?),
                                        SigKind::Method => format!("(.method {})", cx.ids.method.get(&g.name)?),
                                    };
                                    let ps: Vec<_> = g.params.iter().map(|p| Ok(format!("{{ x := {}, ty := {}, optional := {} }}", cx.slot(&p.x)?, emit_tty(cx, &p.ty)?, p.optional))).collect::<Result<_, String>>()?;
                                    format!("(.sig {{ name := {nm}, params := [{}], ret := {} }})", ps.join(", "), emit_tty(cx, &g.ret)?)
                                }
                                CellBody::Stmt(st) => format!("(.stmt {})", stmt(cx, st)?),
                                CellBody::Alg(a) => format!("(.alg {})", alg_id(cx.ids, a)?),
                                CellBody::Expr(e) => format!("(.expr {})", expr(cx, e)?),
                                CellBody::Op(c) => format!("(.op {})", cx.ids.clause.get(c)?),
                                CellBody::Component(f) => format!("(.component {})", cx.ids.field.get(f)?),
                                CellBody::Name(n) => format!("(.name {})", s(n)),
                                CellBody::Lines(cs) => {
                                    let xs: Vec<_> = cs.iter().map(|c| emit_cell_body(cx, c)).collect::<Result<_, _>>()?;
                                    format!("(.lines [{}])", xs.join(", "))
                                }
                                CellBody::Dfn(c) => format!("(.dfn {})", emit_cell_body(cx, c)?),
                                CellBody::Code(c) => format!("(.code {})", emit_cell_body(cx, c)?),
                                CellBody::Link(h, c) => format!("(.link {} {})", s(h), emit_cell_body(cx, c)?),
                                CellBody::Raw(x) => format!("(.raw {})", s(x)),
                                CellBody::Text(x) => format!("(.text {})", s(x)),
                            })
                        }
                        let mut rstrs = Vec::new();
                        for row in &tb.rows {
                            let mut cstrs = Vec::new();
                            for cell in row {
                                cstrs.push(format!("{{ rowspan := {}, colspan := {}, body := {} }}", cell.rowspan, cell.colspan, emit_cell_body(&cx, &cell.body)?));
                            }
                            rstrs.push(format!("{{ cells := [\n      {}] }}", cstrs.join(",\n      ")));
                        }
                        let cap = match &tb.caption { Some(c) => format!("\n  caption := some {}", s(c)), None => String::new() };
                        let sch = match &tb.schema { Some((sc, b)) => format!("(some ({}, {b}))", s(sc)), None => "none".into() };
                        writeln!(
                            body,
                            "def {dname} : Table := {{\n  clause := {}\n  idx := {}{cap}\n  kind := {kind}\n  thead := {}\n  schema := {sch}\n  vars := {}\n  rows := [\n    {}] }}\n",
                            ids.clause.get(&tb.clause)?,
                            tb.idx,
                            tb.thead,
                            vec_arr(&tb.vars, |v| s(v)),
                            rstrs.join(",\n    ")
                        )
                        .unwrap();
                    }
                }
                names.push(dname);
            }
            writeln!(body, "def tables : List Table := [{}]", names.join(", ")).unwrap();
            files.insert(mname.clone(), wrap_mod(&["Ecma.Notation.Tables"], &format!("Ecma.Gen.{mname}"), &body));
            shard_names.push(mname);
        }
        let mut imps = vec!["Ecma.Notation.Tables".to_string()];
        imps.extend(shard_names.iter().map(|m| format!("Ecma.Gen.{m}")));
        let imp_refs: Vec<&str> = imps.iter().map(|x| x.as_str()).collect();
        let lists: Vec<_> = shard_names.iter().map(|m| format!("{m}.tables")).collect();
        let sa: Vec<_> = sort_aliases.iter().map(|(a, b)| format!("({}, {})", s(a), s(b))).collect();
        let tn = vec_arr(&ids.table.names, |x| s(x));
        let body = format!(
            "def tableNames : Array String := {tn}\n\ndef tables : List (List Table) := [{}]\n\ndef sortAliases : Array (String × String) :=\n  #[{}]",
            lists.join(", "),
            sa.join(",\n    ")
        );
        files.insert("Tables".into(), wrap_mod(&imp_refs, "Ecma.Gen", &body));
    }

    // 5. Realm.lean
    {
        let mut body = String::new();
        let emit_rkey = |k: &RKey| match k { RKey::Str(x) => format!("(.str {})", s(x)), RKey::Sym(x) => format!("(.sym {})", s(x)) };
        let emit_rattrs = |a: RAttrs| format!("⟨{}, {}, {}⟩", a.w, a.e, a.c);
        let emit_rval = |v: &RVal| -> Result<String, String> {
            Ok(match v {
                RVal::Undefined => ".undefined".into(),
                RVal::Null => ".null".into(),
                RVal::Bool(b) => format!("(.bool {b})"),
                RVal::Str(x) => format!("(.str {})", s(x)),
                RVal::Number(bits) => format!("(.number {bits})"),
                RVal::Obj(i) => format!("(.obj {i})"),
                RVal::Sym(d) => format!("(.sym {})", s(d)),
                RVal::GlobalThis => ".globalThis".into(),
                RVal::Created(a) => format!("(.created {})", alg_id(ids, a)?),
            })
        };
        let emit_rprop = |p: &RProp| -> Result<String, String> {
            let pv = match &p.val {
                RPVal::Data(v) => format!("(.data {})", emit_rval(v)?),
                RPVal::Accessor(g, st) => format!(
                    "(.accessor {} {})",
                    opt(g, |x| x.to_string()),
                    opt(st, |x| x.to_string())
                ),
            };
            Ok(format!(
                "{{ key := {}, val := {pv}, attrs := {}, clause := {}, annexB := {}, optional := {}, omittable := {} }}",
                emit_rkey(&p.key),
                emit_rattrs(p.attrs),
                ids.clause.get(&p.clause)?,
                p.annex_b,
                p.opt,
                p.omittable
            ))
        };

        let mut onames = Vec::new();
        for o in &realm_objs {
            let dname = format!("o{}", o.idx);
            let ns: Vec<_> = o.names.iter().map(|n| Ok(ids.field.get(n)?.to_string())).collect::<Result<_, String>>()?;
            let ks: Vec<_> = o.keys.iter().map(|n| Ok(ids.field.get(n)?.to_string())).collect::<Result<_, String>>()?;
            let kd = match &o.kind { RKind::Ordinary => ".ordinary".into(), RKind::Exotic(c) => format!("(.exotic {})", ids.clause.get(c)?) };
            let sl: Vec<_> = o.slots.iter().map(|(f, v)| Ok(format!("({}, {})", ids.field.get(f)?, emit_rval(v)?))).collect::<Result<_, String>>()?;
            let fn_ = match &o.fn_ {
                None => "none".into(),
                Some(f) => {
                    let alg = match &f.alg { Some(a) => format!("(some {})", alg_id(ids, a)?), None => "none".into() };
                    format!(
                        "(some {{ alg := {alg}, length := {}, name := {}, pfx := {}, ctor := {}, async := {}, lengthAttrs := {}, nameAttrs := {} }})",
                        f.len, emit_rkey(&f.name), opt(&f.pfx, |p| s(p)), f.ctor, f.is_async, emit_rattrs(f.len_attrs), emit_rattrs(f.name_attrs)
                    )
                }
            };
            let ps: Vec<_> = o.props.iter().map(emit_rprop).collect::<Result<_, String>>()?;
            writeln!(
                body,
                "def {dname} : RObj := {{\n  names := [{}], keys := [{}], path := {}, clause := {}, kind := {kd}, proto := {}, extensible := {},\n  slots := [{}], fn? := {fn_},\n  props := [{}],\n  annexB := {}, optional := {} }}\n",
                ns.join(", "),
                ks.join(", "),
                s(&o.path),
                ids.clause.get(&o.clause)?,
                opt(&o.proto, |p| p.to_string()),
                o.extensible,
                sl.join(", "),
                ps.join(",\n    "),
                o.annex_b,
                o.opt
            )
            .unwrap();
            onames.push(dname);
        }
        writeln!(body, "def objs : List RObj := [{}]\n", onames.join(", ")).unwrap();
        writeln!(body, "def symbols : List String := {}\n", list(&realm_symbols, |x| s(x))).unwrap();
        let cps: Vec<_> = realm_clause_props
            .iter()
            .map(|cp| {
                let ps: Vec<_> = cp.props.iter().map(emit_rprop).collect::<Result<_, String>>()?;
                Ok(format!("({}, [{}])", ids.clause.get(&cp.clause)?, ps.join(",\n    ")))
            })
            .collect::<Result<_, String>>()?;
        writeln!(body, "def clauseProps : List (ClauseId × List RProp) := [{}]", cps.join(",\n  ")).unwrap();
        files.insert("Realm".into(), wrap_mod(&["Ecma.Notation.Realm"], "Ecma.Gen.Realm", &body));
    }

    // 6. Known.lean (symbolic ID constants derived from `Ids`)
    files.insert("Known".into(), crate::known::emit_known(ids)?);

    // 7. Prose*.lean (prose specification models, relations, and laws)
    for (name, txt) in crate::spec_model::emit_lean::emit(spec)? {
        if files.contains_key(&name) {
            return Err(format!("prose module name `{name}` collides with generated module"));
        }
        files.insert(name, txt);
    }

    // Write Ecma/Gen/*.lean atomically on content diff & remove stale .lean files.
    std::fs::create_dir_all(out_dir).map_err(|e| format!("{}: {e}", out_dir.display()))?;
    for entry in std::fs::read_dir(out_dir).map_err(|e| format!("{}: {e}", out_dir.display()))? {
        let p = entry.map_err(|e| e.to_string())?.path();
        let stem = p.file_stem().and_then(|s| s.to_str()).unwrap_or("");
        if p.extension().is_some_and(|e| e == "lean") && !files.contains_key(stem) {
            std::fs::remove_file(&p).map_err(|e| format!("{}: {e}", p.display()))?;
        }
    }
    for (name, txt) in &files {
        let p = out_dir.join(format!("{name}.lean"));
        if std::fs::read_to_string(&p).ok().as_deref() != Some(txt) {
            std::fs::write(&p, txt).map_err(|e| format!("{}: {e}", p.display()))?;
        }
    }
    Ok(())
}
