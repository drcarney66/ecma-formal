pub fn emit_known(ids: &Ids) -> Result<String, String> {
    let mut o = String::from(
        "module\n\n\
         /-! Generated by `crates/spectec` from `spec/spectec/`. Do not edit. -/\n\n\
         @[expose] public section\n\n\
         namespace Ecma.Known\n\n",
    );
    for &(lean_name, kind, spec_name) in KNOWN_IDS {
        let tbl = match kind {
            Kind::Clause => &ids.clause,
            Kind::Enum => &ids.enum_,
            Kind::Field => &ids.field,
            Kind::Nt => &ids.nt,
            Kind::Prim => &ids.prim,
            Kind::Prod => &ids.prod,
            Kind::Sdo => &ids.sdo,
            Kind::Sort => &ids.sort,
        };
        let id = tbl.get(spec_name)?;
        writeln!(o, "@[reducible] def {lean_name} : Nat := {id}").unwrap();
    }
    writeln!(o, "\n/-- Primitive id for unresolved prose (`$\"\"`). -/").unwrap();
    writeln!(o, "@[reducible] def resPrim : Nat := 100000").unwrap();
    writeln!(o, "\nend Ecma.Known").unwrap();
    Ok(o)
}
