//! Emits `lean/Ecma/Grammar/Gen/*.lean` and `tests/parser/grammar_index.txt` from parsed SpecTec rules.

use crate::ast::*;
use crate::ids::Ids;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::path::Path;

const HEADER: &str = "Generated by `crates/spectec` from `spec/spectec/`. Do not edit.";
const SHARD_ALTS: usize = 300;

pub fn lean_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn guillemets(s: &str) -> String {
    format!("«{s}»")
}

fn spell_prod_char(c: char) -> String {
    if c.is_ascii_control() || c == '\u{200C}' || c == '\u{200D}' {
        format!("&#x{:04X};", c as u32)
    } else {
        c.to_string()
    }
}

pub fn terminal_text(t: &Terminal) -> String {
    match t {
        Terminal::Text { text, .. } => {
            if text == "`" {
                "```".into()
            } else {
                let inner: String = text.chars().map(spell_prod_char).collect();
                format!("`{inner}`")
            }
        }
        Terminal::Cp(name) => format!("<{name}>"),
    }
}

fn sym_key(s: &GrammarSym) -> String {
    match s {
        GrammarSym::T(t) => terminal_text(t),
        GrammarSym::Nt(n, args) => {
            if args.is_empty() {
                n.clone()
            } else {
                let xs: Vec<_> = args
                    .iter()
                    .map(|a| {
                        let sg = match a.sign {
                            ParamSign::Plus => "+",
                            ParamSign::Tilde => "~",
                            ParamSign::Quest => "?",
                        };
                        format!("{sg}{}", a.param)
                    })
                    .collect();
                format!("{n}[{}]", xs.join(", "))
            }
        }
    }
}

fn look_item_key(i: &LookItem) -> String {
    match i {
        LookItem::T(t) => terminal_text(t),
        LookItem::NoLT => "[no LineTerminator here]".into(),
    }
}

fn phrase_text(name: &str) -> &'static str {
    match name {
        "anyCodePoint" => "any Unicode code point",
        "idStart" => "any Unicode code point with the Unicode property \u{201c}ID_Start\u{201d}",
        "idContinue" => "any Unicode code point with the Unicode property \u{201c}ID_Continue\u{201d}",
        "leadSurrogate" => "any Unicode code point in the inclusive interval from U+D800 to U+DBFF",
        "trailSurrogate" => "any Unicode code point in the inclusive interval from U+DC00 to U+DFFF",
        "mvAbove10FFFF" => "the MV of |HexDigits| > 0x10FFFF",
        "mvAtMost10FFFF" => "the MV of |HexDigits| ≤ 0x10FFFF",
        "mvLead" => "the MV of |Hex4Digits| is in the inclusive interval from 0xD800 to 0xDBFF",
        "mvTrail" => "the MV of |Hex4Digits| is in the inclusive interval from 0xDC00 to 0xDFFF",
        "mvNonSurrogate" => "the MV of |Hex4Digits| is not in the inclusive interval from 0xD800 to 0xDFFF",
        "groupNumberAtMostCount" => "the CapturingGroupNumber of |DecimalEscape| is ≤ CountLeftCapturingParensWithin(the |Pattern| containing |DecimalEscape|)",
        _ => "",
    }
}

pub fn alt_text(a: &Alt) -> String {
    let mut parts = Vec::new();
    if !a.guard.is_empty() {
        let gs: Vec<_> = a
            .guard
            .iter()
            .map(|g| format!("{}{}", if g.plus { "+" } else { "~" }, g.param))
            .collect();
        parts.push(format!("[{}]", gs.join(", ")));
    }
    for item in &a.rhs {
        match item {
            GrammarItem::Sym(s, opt) => parts.push(format!("{}{}", sym_key(s), if *opt { "?" } else { "" })),
            GrammarItem::Lookahead(la) => {
                let s = match la {
                    Lookahead::Eq(xs) => format!("[lookahead == {}]", xs.iter().map(look_item_key).collect::<Vec<_>>().join(" ")),
                    Lookahead::Ne(xs) => format!("[lookahead != {}]", xs.iter().map(look_item_key).collect::<Vec<_>>().join(" ")),
                    Lookahead::Mem(ss) => {
                        let xs: Vec<_> = ss.iter().map(|s| s.iter().map(look_item_key).collect::<Vec<_>>().join(" ")).collect();
                        format!("[lookahead ∈ {{ {} }}]", xs.join(", "))
                    }
                    Lookahead::NotMem(ss) => {
                        let xs: Vec<_> = ss.iter().map(|s| s.iter().map(look_item_key).collect::<Vec<_>>().join(" ")).collect();
                        format!("[lookahead ∉ {{ {} }}]", xs.join(", "))
                    }
                    Lookahead::NotMemNt(nt) => format!("[lookahead ∉ {nt}]"),
                };
                parts.push(s);
            }
            GrammarItem::NoLT => parts.push("[no LineTerminator here]".into()),
            GrammarItem::Empty => parts.push("[empty]".into()),
            GrammarItem::ButNot(b, Exclusion::Sym(ex)) => {
                parts.push(format!("{} but not {}", sym_key(b), sym_key(ex)));
            }
            GrammarItem::ButNot(b, Exclusion::OneOf { syms, or_sep }) => {
                let sep = if *or_sep { " or " } else { " " };
                let xs: Vec<_> = syms.iter().map(sym_key).collect();
                parts.push(format!("{} but not one of {}", sym_key(b), xs.join(sep)));
            }
            GrammarItem::OnlyIf(c) => parts.push(format!("[> but only if {}]", phrase_text(c))),
            GrammarItem::Phrase(p) => parts.push(format!("> {}", phrase_text(p))),
        }
    }
    parts.join(" ")
}

fn colons_str(c: Colons) -> &'static str {
    match c {
        Colons::One => ":",
        Colons::Two => "::",
        Colons::Three => ":::",
    }
}

fn colons_lean(c: Colons) -> &'static str {
    match c {
        Colons::One => ".one",
        Colons::Two => ".two",
        Colons::Three => ".three",
    }
}

fn cp_lean(c: &str) -> String {
    format!(".{c}")
}

fn emit_terminal_lean(t: &Terminal) -> String {
    match t {
        Terminal::Text { text, alt } => format!(".text {} {alt}", lean_str(text)),
        Terminal::Cp(c) => format!(".cp {}", cp_lean(c)),
    }
}

fn emit_sym_lean(s: &GrammarSym) -> String {
    match s {
        GrammarSym::T(t) => format!(".t ({})", emit_terminal_lean(t)),
        GrammarSym::Nt(n, args) => {
            let as_: Vec<_> = args
                .iter()
                .map(|a| {
                    let sg = match a.sign {
                        ParamSign::Plus => ".plus",
                        ParamSign::Tilde => ".tilde",
                        ParamSign::Quest => ".quest",
                    };
                    format!("⟨{sg}, .{}⟩", a.param)
                })
                .collect();
            format!(".nt .{n} [{}]", as_.join(", "))
        }
    }
}

fn emit_look_item_lean(i: &LookItem) -> String {
    match i {
        LookItem::T(t) => format!(".t ({})", emit_terminal_lean(t)),
        LookItem::NoLT => ".noLT".into(),
    }
}

fn emit_item_lean(i: &GrammarItem) -> String {
    match i {
        GrammarItem::Sym(s, opt) => format!(".sym ({}) {opt}", emit_sym_lean(s)),
        GrammarItem::Lookahead(la) => {
            let inner = match la {
                Lookahead::Eq(xs) => format!(".eq [{}]", xs.iter().map(emit_look_item_lean).collect::<Vec<_>>().join(", ")),
                Lookahead::Ne(xs) => format!(".ne [{}]", xs.iter().map(emit_look_item_lean).collect::<Vec<_>>().join(", ")),
                Lookahead::Mem(ss) => {
                    let xss: Vec<_> = ss.iter().map(|xs| format!("[{}]", xs.iter().map(emit_look_item_lean).collect::<Vec<_>>().join(", "))).collect();
                    format!(".mem [{}]", xss.join(", "))
                }
                Lookahead::NotMem(ss) => {
                    let xss: Vec<_> = ss.iter().map(|xs| format!("[{}]", xs.iter().map(emit_look_item_lean).collect::<Vec<_>>().join(", "))).collect();
                    format!(".notMem [{}]", xss.join(", "))
                }
                Lookahead::NotMemNt(nt) => format!(".notMemNT .{nt}"),
            };
            format!(".lookahead ({inner})")
        }
        GrammarItem::NoLT => ".noLT".into(),
        GrammarItem::Empty => ".empty".into(),
        GrammarItem::ButNot(s, Exclusion::Sym(ex)) => {
            format!(".butNot ({}) (.sym ({}))", emit_sym_lean(s), emit_sym_lean(ex))
        }
        GrammarItem::ButNot(s, Exclusion::OneOf { syms, or_sep }) => {
            let xs: Vec<_> = syms.iter().map(emit_sym_lean).collect();
            format!(".butNot ({}) (.oneOf [{}] {or_sep})", emit_sym_lean(s), xs.join(", "))
        }
        GrammarItem::OnlyIf(c) => format!(".onlyIf .{c}"),
        GrammarItem::Phrase(p) => format!(".phrase .{p}"),
    }
}

fn emit_rule_lean(r: &Rule) -> String {
    let ps: Vec<_> = r.params.iter().map(|p| format!(".{p}")).collect();
    let mut out = format!("/-- `{}` grammar rule. -/\ndef {} : Rule :=\n  ⟨.{}, [{}], {}, ", r.lhs, r.lhs, r.lhs, ps.join(", "), colons_lean(r.colons));
    match &r.body {
        RuleBody::Alts(alts) => {
            out.push_str(".alts [\n");
            for (k, a) in alts.iter().enumerate() {
                let g: Vec<_> = a.guard.iter().map(|g| format!("⟨{}, .{}⟩", g.plus, g.param)).collect();
                let rhs: Vec<_> = a.rhs.iter().map(emit_item_lean).collect();
                let lbl = a.label.as_ref().map_or_else(|| "none".into(), |l| format!("some {}", lean_str(l)));
                let sep = if k + 1 < alts.len() { "," } else { "]⟩\n" };
                writeln!(out, "    ⟨[{}], [{}], {lbl}⟩{sep}", g.join(", "), rhs.join(", ")).unwrap();
            }
        }
        RuleBody::OneOf(rows) => {
            out.push_str(".oneOf [\n");
            for (k, row) in rows.iter().enumerate() {
                let ts: Vec<_> = row.iter().map(emit_terminal_lean).collect();
                let sep = if k + 1 < rows.len() { "," } else { "]⟩\n" };
                writeln!(out, "    [{}]{sep}", ts.join(", ")).unwrap();
            }
        }
    }
    out
}

fn wrap_module(imports: &[&str], doc: &str, ns: &str, body: &str) -> String {
    let mut o = String::from("module\n\n");
    for imp in imports {
        writeln!(o, "public import {imp}").unwrap();
    }
    if !imports.is_empty() {
        o.push('\n');
    }
    writeln!(o, "/-!\n# {doc}\n\n{HEADER}\n-/\n\n@[expose] public section\n\nnamespace {ns}\n\n{body}\nend {ns}").unwrap();
    o
}

fn opt_count(a: &Alt) -> usize {
    a.rhs.iter().filter(|i| matches!(i, GrammarItem::Sym(_, true))).count()
}

fn masks(k: usize) -> Vec<Vec<bool>> {
    (0..(1usize << k))
        .map(|m| (0..k).rev().map(|j| (m >> j) & 1 == 1).collect())
        .collect()
}

fn mask_text(m: &[bool]) -> String {
    if m.is_empty() {
        "-".into()
    } else {
        m.iter().map(|&b| if b { '1' } else { '0' }).collect()
    }
}

pub fn collect_rule_prods(r: &Rule, out: &mut BTreeSet<String>) {
    let gtitle = r.grammar.lean_title();
    let col = colons_str(r.colons);
    match &r.body {
        RuleBody::Alts(alts) => {
            for a in alts {
                let txt = alt_text(a);
                let cname = format!("{} {col} {txt}", r.lhs);
                let k = opt_count(a);
                for mask in masks(k) {
                    out.insert(format!("{gtitle} {} {cname}", mask_text(&mask)));
                }
            }
        }
        RuleBody::OneOf(rows) => {
            for t in rows.iter().flatten() {
                let cname = format!("{} {col} {}", r.lhs, terminal_text(t));
                out.insert(format!("{gtitle} - {cname}"));
            }
        }
    }
}

pub fn emit(spec: &Spec, ids: &Ids, out_dir: &Path, grammar_index_path: Option<&Path>) -> Result<(), String> {
    let mut files: BTreeMap<String, String> = BTreeMap::new();
    let ns = "Ecma.Grammar";

    // 1. Symbols.lean
    {
        let mut body = String::new();
        writeln!(body, "/-- Grammar parameters (§5.1.6), sorted alphabetically from `spec/spectec/`. -/").unwrap();
        writeln!(body, "inductive Param where").unwrap();
        for p in &ids.param.names {
            writeln!(body, "  | {p}").unwrap();
        }
        writeln!(body, "  deriving BEq, DecidableEq, Repr, Inhabited\n").unwrap();
        let pnames: Vec<_> = ids.param.names.iter().map(|s| lean_str(s)).collect();
        writeln!(body, "def Param.names : List String :=\n  [{}]\n", pnames.join(",\n   ")).unwrap();

        writeln!(body, "/-- Grammar nonterminals, sorted alphabetically from `spec/spectec/`. -/").unwrap();
        writeln!(body, "inductive NT where").unwrap();
        for n in &ids.nt.names {
            writeln!(body, "  | {n}").unwrap();
        }
        writeln!(body, "  deriving BEq, DecidableEq, Repr, Inhabited\n").unwrap();
        let nnames: Vec<_> = ids.nt.names.iter().map(|s| lean_str(s)).collect();
        writeln!(body, "def NT.names : List String :=\n  [{}]", nnames.join(",\n   ")).unwrap();

        files.insert("Symbols".into(), wrap_module(&[], "The nonterminals and parameters of ECMA-262", ns, &body));
    }

    // Collect grammar rules in order, plus index items.
    let mut rules_by_g: BTreeMap<GrammarId, Vec<&Rule>> = BTreeMap::new();
    let mut blocks: Vec<&BlockDef> = Vec::new();
    let mut goals: Vec<&GoalDef> = Vec::new();
    let mut covers: Vec<&CoverDef> = Vec::new();
    let mut semis: Vec<&SemiDef> = Vec::new();

    for f in &spec.files {
        for item in &f.items {
            match item {
                TopItem::Rule(r) => rules_by_g.entry(r.grammar).or_default().push(r),
                TopItem::Block(b) => blocks.push(b),
                TopItem::Goal(g) => goals.push(g),
                TopItem::Cover(c) => covers.push(c),
                TopItem::Semi(s) => semis.push(s),
                _ => {}
            }
        }
    }

    let order = [
        GrammarId::NumericString,
        GrammarId::Lexical,
        GrammarId::Syntactic,
        GrammarId::RegExp,
        GrammarId::AnnexB,
        GrammarId::Json,
    ];

    let mut prod_ctors_by_key: BTreeMap<GrammarId, BTreeMap<String, String>> = BTreeMap::new();
    let mut prod_id_seq: Vec<(usize, String)> = Vec::new();
    let mut index_imports: Vec<String> = vec!["Ecma.Grammar.Core".into()];
    let mut index_body = String::new();

    for g in order {
        let rs = rules_by_g.get(&g).cloned().unwrap_or_default();
        let gtitle = g.lean_title();
        let gns = format!("{ns}.Gen.{gtitle}");

        // *Prod.lean & GL production list
        let mut ctor_names: Vec<String> = Vec::new();
        let mut g_ctors_map: BTreeMap<String, String> = BTreeMap::new();

        for r in &rs {
            let col = colons_str(r.colons);
            match &r.body {
                RuleBody::Alts(alts) => {
                    for a in alts {
                        let txt = alt_text(a);
                        let cname = format!("{} {col} {txt}", r.lhs);
                        let k = opt_count(a);
                        for mask in masks(k) {
                            let full_key = format!("{gtitle} {} {cname}", mask_text(&mask));
                            let pid = ids.prod.get(&full_key)?;
                            prod_id_seq.push((pid, full_key.clone()));
                            g_ctors_map.insert(full_key, cname.clone());
                        }
                        ctor_names.push(cname);
                    }
                }
                RuleBody::OneOf(rows) => {
                    for t in rows.iter().flatten() {
                        let cname = format!("{} {col} {}", r.lhs, terminal_text(t));
                        let full_key = format!("{gtitle} - {cname}");
                        let pid = ids.prod.get(&full_key)?;
                        prod_id_seq.push((pid, full_key.clone()));
                        g_ctors_map.insert(full_key, cname.clone());
                        ctor_names.push(cname);
                    }
                }
            }
        }
        prod_ctors_by_key.insert(g, g_ctors_map);

        let mut prod_body = format!("inductive Production where\n");
        for cn in &ctor_names {
            writeln!(prod_body, "  | {}", guillemets(cn)).unwrap();
        }
        prod_body.push_str("  deriving BEq, Inhabited");
        files.insert(format!("{gtitle}Prod"), wrap_module(&[], &format!("The productions of {gtitle}"), &gns, &prod_body));

        // Rule shard module(s)
        let alt_cnt = |r: &Rule| match &r.body {
            RuleBody::Alts(a) => a.len(),
            RuleBody::OneOf(rows) => rows.iter().map(|row| row.len()).sum(),
        };
        let total_alts: usize = rs.iter().map(|r| alt_cnt(r)).sum();
        let mut shards: Vec<(String, Vec<&Rule>)> = Vec::new();
        if total_alts > SHARD_ALTS {
            let mut cur = Vec::new();
            let mut cur_n = 0usize;
            for r in &rs {
                let n = alt_cnt(r);
                if cur_n + n > SHARD_ALTS && !cur.is_empty() {
                    let idx = shards.len() + 1;
                    shards.push((format!("{gtitle}{idx}"), cur));
                    cur = Vec::new();
                    cur_n = 0;
                }
                cur.push(r);
                cur_n += n;
            }
            if !cur.is_empty() {
                let idx = shards.len() + 1;
                shards.push((format!("{gtitle}{idx}"), cur));
            }
        } else {
            shards.push((gtitle.to_string(), rs.clone()));
        }

        for (mod_name, slice) in &shards {
            index_imports.push(format!("{ns}.Gen.{mod_name}"));
            let mut body = String::new();
            for r in slice {
                body.push_str(&emit_rule_lean(r));
                body.push('\n');
            }
            files.insert(mod_name.clone(), wrap_module(&["Ecma.Grammar.Core"], &format!("Rules of {gtitle}"), &gns, &body));
        }

        let rnames: Vec<_> = rs.iter().map(|r| format!("{gtitle}.{}", r.lhs)).collect();
        writeln!(index_body, "def Gen.{gtitle}.rules : List Rule :=\n  [{}]\n", rnames.join(",\n   ")).unwrap();
    }

    index_imports.push(format!("{ns}.Gen.SyntacticProd"));

    // Gen.grammars
    let gram_pairs: Vec<_> = order
        .iter()
        .map(|g| format!("(.{}, Gen.{}.rules)", g.as_str(), g.lean_title()))
        .collect();
    writeln!(index_body, "def Gen.grammars : List (GrammarId × List Rule) :=\n  [{}]\n", gram_pairs.join(", ")).unwrap();

    // Gen.prodIds (RLE) and Gen.prodNext
    let mut rle: Vec<(usize, usize)> = Vec::new();
    for (pid, _) in &prod_id_seq {
        match rle.last_mut() {
            Some((start, len)) if *start + *len == *pid => *len += 1,
            _ => rle.push((*pid, 1)),
        }
    }
    let rle_s: Vec<_> = rle.iter().map(|(a, n)| format!("({a}, {n})")).collect();
    writeln!(index_body, "def Gen.prodIds : List (Nat × Nat) :=\n  [{}]\n", rle_s.join(", ")).unwrap();
    writeln!(index_body, "def Gen.prodNext : Nat := {}\n", ids.prod.names.len()).unwrap();

    // Gen.blocks
    let blk_s: Vec<_> = blocks
        .iter()
        .map(|b| {
            let k = match &b.kind {
                BlockKind::Main => ".main".into(),
                BlockKind::Supplemental(n) => format!(".supplemental .{n}"),
                BlockKind::Overlay { section, mode, cond } => {
                    format!(".overlay .{section} .{mode} .{cond}")
                }
            };
            let rs: Vec<_> = b.rules.iter().map(|r| format!("{}.{}", b.grammar.lean_title(), r)).collect();
            format!("⟨.{}, {}, {k}, [{}]⟩", b.grammar.as_str(), lean_str(&b.clause), rs.join(", "))
        })
        .collect();
    writeln!(index_body, "def Gen.blocks : List Block :=\n  [{}]\n", blk_s.join(",\n   ")).unwrap();

    // Gen.goals
    let goal_s: Vec<_> = goals
        .iter()
        .map(|g| {
            let as_: Vec<_> = g
                .args
                .iter()
                .map(|a| format!("⟨{}, .{}⟩", if a.plus { ".plus" } else { ".tilde" }, a.param))
                .collect();
            format!("⟨.{}, [{}], .{}⟩", g.nt, as_.join(", "), g.src)
        })
        .collect();
    writeln!(index_body, "def Gen.goals : List Goal :=\n  [{}]\n", goal_s.join(",\n   ")).unwrap();

    // Gen.covers & Gen.semis (Syntactic.Production)
    let syn_map = &prod_ctors_by_key[&GrammarId::Syntactic];
    let cov_s: Vec<_> = covers
        .iter()
        .map(|c| {
            let ctor = syn_map
                .get(&c.context)
                .ok_or_else(|| format!("cover references unknown syntactic prod `{}`", c.context))?;
            Ok(format!("⟨.{}, .{}, .{}⟩", guillemets(ctor), c.cover, c.refined))
        })
        .collect::<Result<Vec<_>, String>>()?;
    writeln!(index_body, "def Gen.covers : List (Cover Gen.Syntactic.Production) :=\n  [{}]\n", cov_s.join(",\n   ")).unwrap();

    let semi_s: Vec<_> = semis
        .iter()
        .map(|s| {
            let ctor = syn_map
                .get(&s.prod)
                .ok_or_else(|| format!("semi references unknown syntactic prod `{}`", s.prod))?;
            Ok(format!("⟨.{}, {}, .{}⟩", guillemets(ctor), s.pos, s.kind))
        })
        .collect::<Result<Vec<_>, String>>()?;
    writeln!(index_body, "def Gen.semis : List (SemiSite Gen.Syntactic.Production) :=\n  [{}]\n", semi_s.join(",\n   ")).unwrap();

    let imp_refs: Vec<&str> = index_imports.iter().map(|s| s.as_str()).collect();
    files.insert("Index".into(), wrap_module(&imp_refs, "ECMA-262 grammar index", ns, &index_body));

    // Write Grammar/Gen/*.lean atomically on content diff & remove stale .lean files.
    std::fs::create_dir_all(out_dir).map_err(|e| format!("{}: {e}", out_dir.display()))?;
    for entry in std::fs::read_dir(out_dir).map_err(|e| format!("{}: {e}", out_dir.display()))? {
        let p = entry.map_err(|e| e.to_string())?.path();
        let stem = p.file_stem().and_then(|s| s.to_str()).unwrap_or("");
        if p.extension().is_some_and(|e| e == "lean") && !files.contains_key(stem) {
            std::fs::remove_file(&p).map_err(|e| format!("{}: {e}", p.display()))?;
        }
    }
    for (name, txt) in &files {
        let p = out_dir.join(format!("{name}.lean"));
        if std::fs::read_to_string(&p).ok().as_deref() != Some(txt) {
            std::fs::write(&p, txt).map_err(|e| format!("{}: {e}", p.display()))?;
        }
    }

    if let Some(gidx) = grammar_index_path {
        let mut gtxt = String::from("# Generated by scripts/generate.py (spectec)\n");
        for (pid, key) in &prod_id_seq {
            writeln!(gtxt, "prod {pid} {key}").unwrap();
        }
        if let Some(par) = gidx.parent() {
            std::fs::create_dir_all(par).map_err(|e| format!("{}: {e}", par.display()))?;
        }
        if std::fs::read_to_string(gidx).ok().as_deref() != Some(&gtxt) {
            std::fs::write(gidx, gtxt).map_err(|e| format!("{}: {e}", gidx.display()))?;
        }
    }
    Ok(())
}
