//! The Lean modules: constructor and `List` data only (no `#[…]`, no computed
//! tables), in the forms of `lean/Ecma/Grammar/Core.lean`.

use crate::grammar::{Arg, Body, Colons, Exclusion, Item, LookItem, Lookahead, Rule, Sym, Terminal};
use std::fmt::Write;

pub const HEADER: &str = "Generated by `crates/jsgrammar` from spec.html (`scripts/jsgrammar.py --write`;\n\
docs/parser/GRAMMAR.md). Do not edit.";

pub fn lean_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\u{0000}'..='\u{0009}' | '\u{000B}'..='\u{001F}' | '\u{007F}' | '\u{00AD}' | '\u{200B}'..='\u{200F}' | '\u{2028}' | '\u{2029}' | '\u{FEFF}' => {
                out.push_str(&format!("\\u{:04X}", c as u32))
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// `«text»`, a Lean identifier for any text without `»` or a newline.
pub fn guillemets(s: &str) -> Result<String, String> {
    if s.contains('»') || s.contains('«') || s.contains('\n') {
        return Err(format!("a production text Lean cannot name: {s}"));
    }
    Ok(format!("«{s}»"))
}

fn colons(c: Colons) -> &'static str {
    match c {
        Colons::One => ".one",
        Colons::Two => ".two",
        Colons::Three => ".three",
    }
}

fn terminal(t: &Terminal) -> String {
    match t {
        Terminal::Text(s, alt) => format!(".text {} {alt}", lean_string(s)),
        Terminal::Cp(n) => format!(".cp .{n}"),
    }
}

fn arg(a: &Arg) -> String {
    let s = match a.sign {
        '+' => ".plus",
        '~' => ".tilde",
        _ => ".quest",
    };
    format!("⟨{s}, .{}⟩", a.param)
}

pub fn args(a: &[Arg]) -> String {
    format!("[{}]", a.iter().map(arg).collect::<Vec<_>>().join(", "))
}

fn sym(s: &Sym) -> String {
    match s {
        Sym::T(t) => format!(".t ({})", terminal(t)),
        Sym::Nt(n, a) => format!(".nt .{n} {}", args(a)),
    }
}

fn look_seq(s: &[LookItem]) -> String {
    let items: Vec<String> = s
        .iter()
        .map(|i| match i {
            LookItem::T(t) => format!(".t ({})", terminal(t)),
            LookItem::NoLT => ".noLT".to_string(),
        })
        .collect();
    format!("[{}]", items.join(", "))
}

fn look_set(s: &[Vec<LookItem>]) -> String {
    format!("[{}]", s.iter().map(|q| look_seq(q)).collect::<Vec<_>>().join(", "))
}

fn item(i: &Item) -> String {
    match i {
        Item::Sym(s, opt) => format!(".sym ({}) {opt}", sym(s)),
        Item::Look(l) => {
            let l = match l {
                Lookahead::Eq(s) => format!(".eq {}", look_seq(s)),
                Lookahead::Ne(s) => format!(".ne {}", look_seq(s)),
                Lookahead::Mem(s) => format!(".mem {}", look_set(s)),
                Lookahead::NotMem(s) => format!(".notMem {}", look_set(s)),
                Lookahead::NotMemNT(n) => format!(".notMemNT .{n}"),
            };
            format!(".lookahead ({l})")
        }
        Item::NoLT => ".noLT".to_string(),
        Item::Empty => ".empty".to_string(),
        Item::ButNot(b, e) => {
            let e = match e {
                Exclusion::Sym(s) => format!(".sym ({})", sym(s)),
                Exclusion::OneOf(ss, or) => format!(
                    ".oneOf [{}] {or}",
                    ss.iter()
                        .map(|s| format!("({})", sym(s)))
                        .collect::<Vec<_>>()
                        .join(", ")
                ),
            };
            format!(".butNot ({}) ({e})", sym(b))
        }
        Item::OnlyIf(c) => format!(".onlyIf .{c}"),
        Item::Phrase(p) => format!(".phrase .{p}"),
    }
}

/// `def <lhs> : Rule := …`, with its docstring: the clause, the file (an overlay
/// file's line too) and the rule's text as the file has it. spec.html's and
/// json.emu's rules cite no line, so that text added above a rule leaves its
/// module as it is.
pub fn rule_def(out: &mut String, r: &Rule, clause: &str, file: &str) -> Result<(), String> {
    let raw = r.raw.join("\n");
    if raw.contains("-/") || raw.contains("~~~") {
        return Err(format!("{file}:{}: text a docstring cannot hold", r.line));
    }
    let at = if file == "spec.html" || file == "json.emu" { file.to_string() } else { format!("{file}:{}", r.line) };
    writeln!(out, "/-- `{clause}`, {at}.\n\n~~~\n{raw}\n~~~\n-/").unwrap();
    let params = format!(
        "[{}]",
        r.params.iter().map(|p| format!(".{p}")).collect::<Vec<_>>().join(", ")
    );
    let body = match &r.body {
        Body::Alts(alts) => {
            let mut b = String::from(".alts [");
            for (k, a) in alts.iter().enumerate() {
                let guard = format!(
                    "[{}]",
                    a.guard
                        .iter()
                        .map(|(plus, p)| format!("⟨{plus}, .{p}⟩"))
                        .collect::<Vec<_>>()
                        .join(", ")
                );
                let label = match &a.label {
                    None => "none".to_string(),
                    Some(l) => format!("some {}", lean_string(l)),
                };
                let rhs: Vec<String> = a.rhs.iter().map(item).collect();
                write!(
                    b,
                    "{}\n    ⟨{guard}, [{}], {label}⟩",
                    if k == 0 { "" } else { "," },
                    rhs.join(", ")
                )
                .unwrap();
            }
            b.push(']');
            b
        }
        Body::OneOf(rows) => {
            let rows: Vec<String> = rows
                .iter()
                .map(|r| {
                    format!(
                        "[{}]",
                        r.iter()
                            .map(|t| format!("({})", terminal(t)))
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                })
                .collect();
            format!(".oneOf [\n    {}]", rows.join(",\n    "))
        }
    };
    writeln!(
        out,
        "def {} : Rule :=\n  ⟨.{}, {params}, {}, {body}⟩\n",
        r.lhs,
        r.lhs,
        colons(r.colons)
    )
    .unwrap();
    Ok(())
}

/// A module's text: `module`, its imports, the exposed section, a module
/// docstring, and `body` in `namespace`.
pub fn module(imports: &[String], doc: &str, namespace: &str, body: &str) -> String {
    let mut out = String::from("module\n\n");
    for i in imports {
        writeln!(out, "public import {i}").unwrap();
    }
    if !imports.is_empty() {
        out.push('\n');
    }
    writeln!(
        out,
        "@[expose] public section\n\n/-!\n{doc}\n\n{HEADER}\n-/\n\nnamespace {namespace}\n"
    )
    .unwrap();
    out.push_str(body);
    writeln!(out, "end {namespace}").unwrap();
    out
}
