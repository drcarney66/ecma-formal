/// The most steps a data module holds.
pub const SHARD_STEPS: usize = 300;

thread_local! {
    /// each overlay erratum's id, by its index in the overlay (`Decls::erratum_ids`); none: the index
    static ERRATA: std::cell::RefCell<Vec<usize>> = const { std::cell::RefCell::new(Vec::new()) };
    /// each spec.html clause's id, by its index in `Spec::clauses` (`Decls::cids`); none: the index
    static CLAUSES: std::cell::RefCell<Vec<usize>> = const { std::cell::RefCell::new(Vec::new()) };
    /// each right-hand side's id, by its position in GL's `prods` (`Decls::prod_ids`); none: the position
    static PRODS: std::cell::RefCell<Vec<usize>> = const { std::cell::RefCell::new(Vec::new()) };
    /// each table's id, by its index among the scanned tables (`Decls::table_ids`); none: the index
    static TABLES: std::cell::RefCell<Vec<usize>> = const { std::cell::RefCell::new(Vec::new()) };
}

/// Prints the data's erratum indices, `Spec::clauses` indices, GL positions and table indices as their ids
/// (`Decls::erratum_ids`, `Decls::cids`, `Decls::prod_ids`, `Decls::table_ids`).
pub fn set_ids(d: &crate::decls::Decls) {
    ERRATA.with(|m| *m.borrow_mut() = d.erratum_ids.clone());
    CLAUSES.with(|m| *m.borrow_mut() = d.cids.clone());
    PRODS.with(|m| *m.borrow_mut() = d.prod_ids.clone());
    TABLES.with(|m| *m.borrow_mut() = d.table_ids.clone());
}

/// The production id of the right-hand side at position `p` of GL's `prods`.
pub fn pid(p: usize) -> usize {
    PRODS.with(|m| m.borrow().get(p).copied().unwrap_or(p))
}

/// The table id of the `t`th scanned table.
pub fn tid(t: usize) -> usize {
    TABLES.with(|m| m.borrow().get(t).copied().unwrap_or(t))
}

/// The clause id of `Spec::clauses[c]`.
pub fn cid(c: usize) -> usize {
    CLAUSES.with(|m| m.borrow().get(c).copied().unwrap_or(c))
}

/// The erratum id of the overlay's `e`th erratum.
pub fn eid(e: usize) -> usize {
    ERRATA.with(|m| m.borrow().get(e).copied().unwrap_or(e))
}

pub const HEADER: &str = "Generated by `crates/spec-gen` from spec.html (`scripts/gen_spec.py --write`). Do not edit.";

pub fn s(x: &str) -> String {
    let mut out = String::from("\"");
    for c in x.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

pub(crate) fn list<T>(xs: &[T], f: impl Fn(&T) -> String) -> String {
    format!("[{}]", xs.iter().map(f).collect::<Vec<_>>().join(", "))
}

fn opt<T>(x: &Option<T>, f: impl Fn(&T) -> String) -> String {
    match x {
        Some(v) => format!("(some {})", f(v)),
        None => "none".into(),
    }
}

fn b(x: bool) -> &'static str {
    if x {
        "true"
    } else {
        "false"
    }
}

fn attr(a: &Attr) -> String {
    format!("⟨{}, {}⟩", s(&a.key), opt(&a.value, |v| s(v)))
}

fn attrs(a: &[Attr]) -> String {
    list(a, attr)
}

fn sub(x: &Sub) -> &'static str {
    match x {
        Sub::None => ".none",
        Sub::F => ".f",
        Sub::Z => ".z",
    }
}

fn sign(x: &Sign) -> &'static str {
    match x {
        Sign::None => ".none",
        Sign::Plus => ".plus",
        Sign::Minus => ".minus",
    }
}

fn numeral(n: &Numeral) -> String {
    match n {
        Numeral::Dec(n) => format!("(.dec {n})"),
        Numeral::Hex(n, d) => format!("(.hex {n} {})", s(d)),
        Numeral::Frac(w, f, n) => format!("(.frac {w} {f} {n})"),
    }
}

fn mag(m: &Mag) -> String {
    match m {
        Mag::Num(n) => format!("(.num {})", numeral(n)),
        Mag::Inf => ".inf".into(),
    }
}

fn val(v: &ValLit) -> String {
    match v {
        ValLit::Undefined => ".undefined".into(),
        ValLit::Null => ".null".into(),
        ValLit::True => ".true".into(),
        ValLit::False => ".false".into(),
        ValLit::This => ".this".into(),
        ValLit::Str(x, w) => format!("(.str {} {})", s(x), s(w)),
        ValLit::NaN(x) => format!("(.nan {})", sub(x)),
        ValLit::Num(sg, m, x) => format!("(.num {} {} {})", sign(sg), mag(m), sub(x)),
        ValLit::Err(i) => format!("(.err {i})"),
        ValLit::BigN(n) => format!("(.bigN {})", numeral(n)),
    }
}

fn article(a: &Article) -> &'static str {
    match a {
        Article::The => ".the",
        Article::None => ".none",
    }
}

fn alt(f: &AltForm) -> &'static str {
    match f {
        AltForm::Either => ".either",
        AltForm::OneOf => ".oneOf",
        AltForm::Or => ".or",
        AltForm::Neither => ".neither",
    }
}

fn conn(f: &ConnForm) -> &'static str {
    match f {
        ConnForm::Plain => ".plain",
        ConnForm::Comma => ".comma",
        ConnForm::OrIf => ".orIf",
        ConnForm::Following => ".following",
    }
}

fn conj(c: &Conj) -> &'static str {
    match c {
        Conj::And => ".and",
        Conj::Or => ".or",
    }
}

fn listform(f: &ListForm) -> String {
    match f {
        ListForm::Paren => ".paren".into(),
        ListForm::Comma => ".comma".into(),
        ListForm::English(c) => format!("(.english {})", conj(c)),
        ListForm::Bullets => ".bullets".into(),
    }
}

fn args(xs: &[Expr]) -> String {
    list(xs, expr)
}

pub fn ch(c: &Channel) -> String {
    let o = |p: &Option<Id>| opt(p, |x| x.to_string());
    match c {
        Channel::Pending => ".pending".into(),
        Channel::Upstream(r, p) => format!("(.upstream {r} {})", o(p)),
        Channel::Prim(p, w) => format!("(.prim {p} {w})"),
        Channel::Annotated(k, p) => format!("(.annotated {k} {})", o(p)),
    }
}

pub fn expr(e: &Expr) -> String {
    match e {
        Expr::Var(x) => format!("(.var {x})"),
        Expr::Val(v) => format!("(.val {})", val(v)),
        Expr::Math(sg, m) => format!("(.math {} {})", sign(sg), mag(m)),
        Expr::Enum(i) => format!("(.enum {i})"),
        Expr::Intrinsic(i) => format!("(.intrinsic {i})"),
        Expr::FieldName(i) => format!("(.fieldName {i})"),
        Expr::Nt(i, xs) => format!("(.nt {i} {})", list(xs, |(p, b)| format!("({p}, {})", self::b(*b)))),
        Expr::Param(p) => format!("(.param {p})"),
        Expr::Prod(ps, x) => format!("(.prod {} {})", list(ps, |&p| pid(p).to_string()), s(x)),
        Expr::CodeUnit(n, d, nm) => format!("(.codeUnit {n} {} {})", s(d), opt(nm, |x| s(x))),
        Expr::CodePoint(n, d, nm) => format!("(.codePoint {n} {} {})", s(d), opt(nm, |x| s(x))),
        Expr::Code(x, w) => format!("(.code {} {})", s(x), s(w)),
        Expr::Call(Callee::Alg(c), a) => format!("(.call (.alg ⟨{c}, 0⟩) {})", args(a)),
        Expr::Call(Callee::Prim(p), a) => format!("(.call (.prim {p}) {})", args(a)),
        Expr::Sdo(i, a, x, xs) => format!("(.sdo {i} {} {} {})", article(a), expr(x), args(xs)),
        Expr::Component(i, a, x) => format!("(.component {i} {} {})", article(a), expr(x)),
        Expr::Field(x, f) => format!("(.field {} {f})", expr(x)),
        Expr::IMethod(x, m, a) => format!("(.imethod {} {m} {})", expr(x), args(a)),
        Expr::CMethod(x, m, a) => format!("(.cmethod {} {m} {})", expr(x), args(a)),
        Expr::Apply(f, a) => format!("(.apply {} {})", expr(f), args(a)),
        Expr::Index(x, i) => format!("(.index {} {})", expr(x), expr(i)),
        Expr::Q(x) => format!("(.q {})", expr(x)),
        Expr::Bang(x) => format!("(.bang {})", expr(x)),
        Expr::BangAt(r, x) => format!("(.bangAt {} {})", eid(*r), expr(x)),
        Expr::Erratum(r, s, x) => format!("(.erratum {} {s} {})", eid(*r), expr(x)),
        Expr::Neg(x) => format!("(.un .neg {})", expr(x)),
        Expr::Bin(o, x, y) => {
            let o = match o {
                BinOp::Add => ".add",
                BinOp::Sub => ".sub",
                BinOp::Mul => ".mul",
                BinOp::Div => ".div",
                BinOp::Modulo => ".modulo",
                BinOp::Pow => ".pow",
                BinOp::Plus => ".plus",
                BinOp::Times => ".times",
            };
            format!("(.bin {o} {} {})", expr(x), expr(y))
        }
        Expr::Paren(x) => format!("(.paren {})", expr(x)),
        Expr::List(xs) => format!("(.list {})", args(xs)),
        Expr::Record(a, k, fs) => format!("(.record {} {} {})", article(a), opt(k, |k| k.to_string()), list(fs, |(f, x)| format!("({f}, {})", expr(x)))),
        Expr::Annot(a, x) => format!("(.annot {} {})", attrs(a), expr(x)),
        Expr::Xref(..) => format!("(.xref {})", xref_struct(e)),
        Expr::Closure(site) => format!("(.closure {site})"),
        Expr::Term(t) => format!("(.term {})", s(t)),
        Expr::Table(t, x) => format!("(.table {} {})", tid(*t), xref_struct(x)),
        Expr::Definition(x, a) => format!("(.definition {} {a})", xref_struct(x)),
        Expr::TableStep(t, k, x) => format!("(.tableStep {} {} {})", tid(*t), expr(k), xref_struct(x)),
        Expr::Extreme(mx, x, t, c) => format!("(.extreme {mx} {x} {} {})", ty(t), cond(c)),
        Expr::ResumedWith(x) => format!("(.resumedWith {})", expr(x)),
        Expr::ThisValue(bare) => format!("(.thisValue {})", b(*bare)),
        Expr::NewTarget => ".newTarget".into(),
        Expr::ThisNode => ".thisNode".into(),
        Expr::Child(k, n, x) => format!("(.child {k} {n} {})", s(x)),
        Expr::ChildOf(y, n, x) => format!("(.childOf {} {n} {})", expr(y), s(x)),
        Expr::Phrase(p, hs) => format!("(.phrase {p} {})", holes(hs)),
        Expr::Prose(c, ps) => format!("(.prose {} {})", ch(c), parts(ps)),
    }
}

fn pred(p: &Pred) -> String {
    match p {
        Pred::IsVal(n, f, vs) => format!("(.isVal {} {} {})", b(*n), alt(f), args(vs)),
        Pred::IsTy(n, f, ts) => format!("(.isTy {} {} {})", b(*n), alt(f), list(ts, ty)),
        Pred::Phrase(p, hs) => format!("(.phrase {p} {})", holes(hs)),
    }
}

fn preds(rest: &[(Conj, Pred)]) -> String {
    list(rest, |(c, p)| format!("({}, {})", conj(c), pred(p)))
}

pub fn cond(c: &Cond) -> String {
    match c {
        Cond::Preds(e, p, r) => format!("(.preds {} {} {})", expr(e), pred(p), preds(r)),
        Cond::Rel(o, x, y) => {
            let o = match o {
                RelOp::Lt => ".lt",
                RelOp::Le => ".le",
                RelOp::Gt => ".gt",
                RelOp::Ge => ".ge",
                RelOp::Eq => ".eq",
                RelOp::Ne => ".ne",
            };
            format!("(.rel {o} {} {})", expr(x), expr(y))
        }
        Cond::And(f, cs) => format!("(.and {} {})", conn(f), list(cs, cond)),
        Cond::Or(f, cs) => format!("(.or {} {})", conn(f), list(cs, cond)),
        Cond::Paren(x) => format!("(.paren {})", cond(x)),
        Cond::Alg(c, i, _) => format!("(.alg ⟨{c}, {i}⟩)"),
        Cond::Phrase(p, hs) => format!("(.phrase {p} {})", holes(hs)),
        Cond::Prose(c, ps) => format!("(.prose {} {})", ch(c), parts(ps)),
    }
}

pub fn ty(t: &TyExpr) -> String {
    match t {
        TyExpr::Sort(a, m, x, w) => format!("(.sort {} {} {x} {})", s(a), list(m, |x| x.to_string()), s(w)),
        TyExpr::ListOf(a, x) => format!("(.listOf {} {})", s(a), ty(x)),
        TyExpr::Union(f, c, ts) => format!("(.union {} {} {})", alt(f), conn(c), list(ts, ty)),
        TyExpr::Completion(x) => format!("(.completion {})", opt(x, |x| ty(x))),
        TyExpr::Interval(x, lo, hi) => format!("(.interval {} {} {})", ty(x), expr(lo), expr(hi)),
        TyExpr::Value(e) => format!("(.value {})", expr(e)),
        TyExpr::Var(a, x) => format!("(.var {} {x})", s(a)),
        TyExpr::Nt(a, n, x) => format!("(.nt {} {n} {})", s(a), s(x)),
        TyExpr::Record(fs) => format!("(.record {})", list(fs, |(f, x)| format!("({f}, {})", ty(x)))),
        TyExpr::That(x, p, r) => format!("(.that {} {} {})", ty(x), pred(p), preds(r)),
        TyExpr::Phrase(p, hs) => format!("(.phrase {p} {})", holes(hs)),
        TyExpr::Prose(ps) => format!("(.prose {})", parts(ps)),
    }
}

pub(crate) fn hole(h: &Hole) -> String {
    match h {
        Hole::E(e) => format!("(.e {})", expr(e)),
        Hole::C(c) => format!("(.c {})", cond(c)),
        Hole::Bc(xs, c) => format!("(.bc {} {})", list(xs, |x| x.to_string()), cond(c)),
        Hole::T(t) => format!("(.t {})", ty(t)),
        Hole::B(x) => format!("(.b {x})"),
        Hole::W(i) => format!("(.w {i})"),
        Hole::L(f, xs) => format!("(.l {} {})", listform(f), args(xs)),
        Hole::Text(x) => format!("(.text {})", s(x)),
        Hole::Field(f) => format!("(.field {f})"),
    }
}

pub fn holes(hs: &[Hole]) -> String {
    list(hs, hole)
}

pub fn parts(ps: &[Part]) -> String {
    list(ps, |p| match p {
        Part::Text(x) => format!(".text {}", s(x)),
        Part::Hole(h) => format!(".hole {}", hole(h)),
    })
}

fn body(bd: &Body) -> String {
    match bd {
        Body::Inline(st) => format!("(.inline {})", stmt(st)),
        Body::Block(ns) => format!("(.block {})", nodes(ns)),
    }
}

fn arm(a: &Arm) -> String {
    format!(".mk {} {} {}", attrs(&a.attrs), opt(&a.cond, cond), body(&a.body))
}

/// An `emu-xref` as an `Xref`.
fn xref_struct(e: &Expr) -> String {
    let Expr::Xref(h, f, c) = e else { panic!("an xref: {e:?}") };
    let f = match f {
        XrefForm::Plain => ".plain".to_string(),
        XrefForm::Title => ".title".to_string(),
        XrefForm::Content(c) => format!("(.content {})", s(c)),
    };
    format!("⟨{}, {f}, {}⟩", s(h), opt(c, |c| c.to_string()))
}

pub fn stmt(st: &Stmt) -> String {
    match st {
        Stmt::Let(x, e) => format!("(.let_ {x} {})", expr(e)),
        Stmt::Set(p, e) => {
            let p = match p {
                Place::Var(x) => format!("(.var {x})"),
                Place::Field(e, f) => format!("(.field {} {f})", expr(e)),
                Place::Expr(e) => format!("(.expr {})", expr(e)),
            };
            format!("(.set {p} {})", expr(e))
        }
        Stmt::Ret(e) => format!("(.ret {})", opt(e, expr)),
        Stmt::Perform(e) => format!("(.perform {})", expr(e)),
        Stmt::If(c, bd, arms, els) => format!("(.if_ {} {} {} {})", cond(c), body(bd), list(arms, |a| format!("({})", arm(a))), opt(els, |a| format!("({})", arm(a)))),
        Stmt::IfElse(c, x, y) => format!("(.ifElse {} {} {})", cond(c), stmt(x), stmt(y)),
        Stmt::Assert(c) => format!("(.assert {})", cond(c)),
        Stmt::AssertAt(r, c) => format!("(.assertAt {} {})", r.map_or("none".to_string(), |r| format!("(some {})", eid(r))), cond(c)),
        Stmt::AssertIf(c, d) => format!("(.assertIf {} {})", cond(c), cond(d)),
        Stmt::Unreachable(v) => format!("(.unreachable {v})"),
        Stmt::ThrowErr(i) => format!("(.throwErr {i})"),
        Stmt::ThrowVal(e) => format!("(.throwVal {})", expr(e)),
        Stmt::Note(ps) => format!("(.note {})", parts(ps)),
        Stmt::Repeat(ns) => format!("(.repeat_ {})", nodes(ns)),
        Stmt::RepeatWhile(c, ns) => format!("(.repeatWhile {} {})", cond(c), nodes(ns)),
        Stmt::RepeatUntil(c, ns) => format!("(.repeatUntil {} {})", cond(c), nodes(ns)),
        Stmt::ForEach(x, t, l, r, bd) => format!("(.forEach {x} {} {} {} {})", opt(t, ty), expr(l), b(*r), body(bd)),
        Stmt::ForEachRec(fs, x, l, bd) => format!("(.forEachRec {} {x} {} {})", list(fs, |f| f.to_string()), expr(l), body(bd)),
        Stmt::Mutate(p, hs) => format!("(.mutate {p} {})", holes(hs)),
        Stmt::ForSuchThat(x, t, c, o, bd) => format!("(.forSuchThat {x} {} {} {} {})", ty(t), cond(c), opt(o, |o| o.to_string()), body(bd)),
        Stmt::ForKeys(x, o, c, k, bd) => format!("(.forKeys {x} {} {} {k} {})", expr(o), cond(c), body(bd)),
        Stmt::ForIndex(x, l, bd) => format!("(.forIndex {x} {} {})", expr(l), body(bd)),
        Stmt::ForChildren(x, bd) => format!("(.forChildren {x} {})", body(bd)),
        Stmt::ForChildrenOf(x, e, bd) => format!("(.forChildrenOf {x} {} {})", expr(e), body(bd)),
        Stmt::RepeatN(e, ns) => format!("(.repeatN {} {})", expr(e), nodes(ns)),
        Stmt::ForRange(x, lo, li, hi, hii, d, bd) => format!("(.forRange {x} {} {} {} {} {} {})", expr(lo), b(*li), expr(hi), b(*hii), b(*d), body(bd)),
        Stmt::RetSee(e, x) => {
            let x = match x {
                Expr::Xref(h, f, c) => {
                    let f = match f {
                        XrefForm::Plain => ".plain".to_string(),
                        XrefForm::Title => ".title".to_string(),
                        XrefForm::Content(t) => format!("(.content {})", s(t)),
                    };
                    format!("⟨{}, {f}, {}⟩", s(h), opt(c, |c| c.to_string()))
                }
                _ => "default".into(),
            };
            format!("(.retSee {} {x})", expr(e))
        }
        Stmt::Macro(c, a) => format!("(.macro ⟨{c}, 0⟩ {})", args(a)),
        Stmt::Suspend(e, v) => format!("(.suspend {} {v})", expr(e)),
        Stmt::Push(e, v) => format!("(.push {} {v})", expr(e)),
        Stmt::Remove(e, v) => format!("(.remove {} {v})", expr(e)),
        Stmt::RemoveRestore(e, r) => format!("(.removeRestore {} {})", expr(e), expr(r)),
        Stmt::ResumeTop => ".resumeTop".into(),
        Stmt::ResumeLet(c, k, x, a) => format!("(.resumeLet {} {} {x} {})", expr(c), expr(k), attrs(a)),
        Stmt::Resume(c, k) => format!("(.resume {} {})", expr(c), expr(k)),
        Stmt::SetCodeState(c, k) => format!("(.setCodeState {} {})", expr(c), expr(k)),
        Stmt::FindSuchThat(x, t, c, r, f) => format!("(.findSuchThat {x} {} {} {} {})", ty(t), cond(c), s(r), stmt(f)),
        Stmt::LetSuchThat(xs, c, os) => format!("(.letSuchThat {} {} {})", list(xs, |x| x.to_string()), cond(c), list(os, |(b, e)| format!("({b}, {})", expr(e)))),
        Stmt::Readings(e, lit, alts) => format!(
            "(.readings {} {} {})",
            eid(*e),
            stmt(lit),
            list(alts, |(r, ns)| format!("({}, {})", reading(*r), nodes(ns)))
        ),
        Stmt::SyntaxError(e, c, u) => {
            let u = opt(u, |(f, c)| {
                let f = match f {
                    UnlessForm::Plain => ".plain",
                    UnlessForm::Comma => ".comma",
                    UnlessForm::Optional => ".optional",
                };
                format!("({f}, {})", cond(c))
            });
            format!("(.syntaxError {} {} {u})", b(*e), cond(c))
        }
        Stmt::Phrase(p, hs) => format!("(.phrase {p} {})", holes(hs)),
        Stmt::Prose(c, ps) => format!("(.prose {} {})", ch(c), parts(ps)),
        Stmt::WithSteps(st, ns) => format!("(.withSteps {} {})", stmt(st), nodes(ns)),
    }
}

pub(crate) fn reading(r: Reading) -> &'static str {
    match r {
        Reading::Literal => ".literal",
        Reading::Test262 => ".test262",
        Reading::Proposed => ".proposed",
        Reading::Definition => ".definition",
    }
}

fn node(n: &Node) -> String {
    format!(".mk {} {}", attrs(&n.attrs), stmt(&n.stmt))
}

pub(crate) fn nodes(ns: &[Node]) -> String {
    list(ns, |n| format!("({})", node(n)))
}

/// Steps in a list of nodes, nested ones and arms included.
pub fn count_steps(ns: &[Node]) -> usize {
    fn st(s: &Stmt) -> usize {
        match s {
            Stmt::If(_, b, arms, els) => {
                let bd = |b: &Body| if let Body::Block(ns) = b { count_steps(ns) } else { 0 };
                bd(b) + arms.iter().chain(els.iter()).map(|a| 1 + bd(&a.body)).sum::<usize>()
            }
            Stmt::Repeat(ns) | Stmt::RepeatWhile(_, ns) | Stmt::RepeatUntil(_, ns) => count_steps(ns),
            Stmt::ForEach(.., Body::Block(ns)) | Stmt::ForEachRec(.., Body::Block(ns)) => count_steps(ns),
            Stmt::ForSuchThat(.., b) | Stmt::ForKeys(.., b) | Stmt::ForIndex(_, _, b) | Stmt::ForChildren(_, b) | Stmt::ForChildrenOf(_, _, b) | Stmt::ForRange(.., b) => match b {
                Body::Block(ns) => count_steps(ns),
                Body::Inline(_) => 0,
            },
            Stmt::RepeatN(_, ns) => count_steps(ns),
            Stmt::Readings(_, lit, _) => st(lit),
            Stmt::WithSteps(_, ns) => count_steps(ns),
            _ => 0,
        }
    }
    ns.iter().map(|n| 1 + st(&n.stmt)).sum()
}

pub(crate) fn closures(cs: &[CloLit]) -> String {
    let lit = |c: &CloLit| {
        let k = match c.kind {
            CloKind::Abstract => ".abstract",
            CloKind::Job => ".job",
            CloKind::Matcher => ".matcher",
            CloKind::MatcherContinuation => ".matcherContinuation",
            CloKind::ReadModifyWrite => ".readModifyWrite",
        };
        format!(
            "{{ kind := {k}, atomic := {}, params := {}, caps := {}, body := {}{} }}",
            b(c.atomic),
            opt(&c.params, |p| list(p, |x| x.to_string())),
            list(&c.caps, |x| x.to_string()),
            nodes(&c.body),
            c.frame.map_or(String::new(), |(t, nt, a)| format!(", frame := some ({t}, {nt}, {a})"))
        )
    };
    format!("#[{}]", cs.iter().map(lit).collect::<Vec<_>>().join(",\n    "))
}

fn header(h: &crate::data::Hdr) -> String {
    let params = list(&h.params, |(x, t, op, r)| format!("{{ x := {x}, ty := {}, optional := {}, rest := {} }}", tyo(t), b(*op), b(*r)));
    format!(
        "{{ kind := {}, params := {params}, ret := {}, recv := {}, desc := {} }}",
        kind(h.kind),
        tyo(&h.ret),
        opt(&h.recv, |(x, t)| format!("({x}, {})", ty(t))),
        if h.desc.is_empty() { "[]".to_string() } else { format!("[.text {}]", s(&h.desc)) }
    )
}

fn kind(k: &str) -> String {
    format!(".{k}")
}

fn tyo(t: &Option<TyExpr>) -> String {
    opt(t, ty)
}

/// The clause group of a section number: `7.1.2` -> `S7_1`, `B.3.2` -> `SB_3`.
pub fn group(number: &str) -> String {
    let parts: Vec<&str> = number.split('.').take(2).collect();
    format!("S{}", parts.join("_"))
}

/// One datum: an algorithm, or an SDO row.
pub struct Datum<'a> {
    pub alg: &'a Alg,
    /// an equation row instead of the algorithm
    pub eq: Option<&'a crate::data::EqRow>,
    pub name: String,
    pub sdo: Option<String>,
    pub steps: usize,
}

/// The modules: name -> data, in document order.
pub fn modules<'a>(sp: &Spec, dt: &'a Data) -> BTreeMap<String, Vec<Datum<'a>>> {
    let mut groups: Vec<(String, Vec<Datum>)> = Vec::new();
    let mut sdo_rows: BTreeMap<String, usize> = BTreeMap::new();
    let mut items: Vec<(usize, &Alg, Option<&crate::data::EqRow>)> = dt.algs.iter().map(|a| (sp.algs[a.alg].line, a, None)).collect();
    let anchor = &dt.algs[0];
    items.extend(dt.eqs.iter().filter(|e| e.exception.is_none()).map(|e| (sp.eqs[e.eq].line, anchor, Some(e))));
    items.sort_by_key(|x| x.0);
    for (_, a, eq) in items {
        if let Some(e) = eq {
            let c = &sp.clauses[e.clause];
            let op = dt.decls.sdos.name(e.sdo).to_string();
            let k = sdo_rows.entry(op.clone()).or_default();
            *k += 1;
            let d = Datum { alg: a, eq: Some(e), name: format!("{op}.{k}"), sdo: Some(op), steps: 1 };
            let g = group(&c.number);
            match groups.last_mut() {
                Some((g0, v)) if *g0 == g => v.push(d),
                _ => groups.push((g, vec![d])),
            }
            continue;
        }
        let c = &sp.clauses[a.clause];
        let al = &sp.algs[a.alg];
        let g = group(&c.number);
        let op = c.op().unwrap_or_else(|| c.id.clone());
        let ext = a.ext.as_ref();
        let op = ext.map_or(op, |e| e.op.clone());
        let (name, sdo) = if (a.hdr.kind == "sdo" || ext.is_some()) && al.prod.is_some() {
            let k = sdo_rows.entry(op.clone()).or_default();
            *k += 1;
            (format!("{op}.{k}"), Some(op))
        } else {
            (op, None)
        };
        let steps = count_steps(&a.body) + a.closures.iter().map(|c| count_steps(&c.body)).sum::<usize>();
        let d = Datum { alg: a, eq: None, name, sdo, steps };
        match groups.last_mut() {
            Some((g0, v)) if *g0 == g => v.push(d),
            _ => groups.push((g, vec![d])),
        }
    }
    // shard, and make names unique within a module
    let mut out = BTreeMap::new();
    let mut seen_groups: BTreeMap<String, usize> = BTreeMap::new();
    for (g, ds) in groups {
        let n = seen_groups.entry(g.clone()).or_default();
        *n += 1;
        let g = if *n > 1 { format!("{g}_{n}") } else { g };
        let mut shards: Vec<Vec<Datum>> = vec![vec![]];
        let mut count = 0;
        for d in ds {
            if count + d.steps > SHARD_STEPS && !shards.last().unwrap().is_empty() {
                shards.push(vec![]);
                count = 0;
            }
            count += d.steps;
            shards.last_mut().unwrap().push(d);
        }
        let k = shards.len();
        for (i, mut sh) in shards.into_iter().enumerate() {
            let mut names: BTreeMap<String, usize> = BTreeMap::new();
            for d in &mut sh {
                let c = names.entry(d.name.clone()).or_default();
                *c += 1;
                if *c > 1 {
                    d.name = format!("{}.{}", d.name, c);
                }
            }
            let m = if k > 1 { format!("{g}_part{}", i + 1) } else { g.clone() };
            out.insert(m, sh);
        }
    }
    out
}

fn guill(x: &str) -> String {
    format!("«{x}»")
}

/// A data module's source.
pub fn module(sp: &Spec, dt: &Data, name: &str, ds: &[Datum]) -> Result<String, String> {
    let mut o = String::new();
    writeln!(o, "module\n\npublic import Ecma.Notation.Syntax\n\n/-! {HEADER} -/\n\n@[expose] public section\n\nnamespace Ecma.Gen.{name}\n\nopen Ecma\n").unwrap();
    let mut algs = Vec::new();
    let mut rows = Vec::new();
    for d in ds {
        if let Some(e) = d.eq {
            let q = &sp.eqs[e.eq];
            let vars = format!("#[{}]", e.vars.names.iter().map(|v| s(v)).collect::<Vec<_>>().join(", "));
            writeln!(
                o,
                "/-- {} (§{}) -/\ndef {} : SdoRow := {{\n  id := ⟨{}, {}⟩\n  sdo := {}\n  prods := {}\n  keys := {}\n  form := .equation\n  indent := {}\n  vars := {vars}\n  body := {}\n  closures := #[] }}\n",
                sp.clauses[e.clause].id,
                sp.clauses[e.clause].number,
                guill(&d.name),
                cid(e.clause),
                e.idx,
                e.sdo,
                list(&e.prods, |&p| pid(p).to_string()),
                list(&e.keys, |k| s(k)),
                q.indent,
                nodes(&e.body)
            )
            .unwrap();
            rows.push(guill(&d.name));
            continue;
        }
        let a = d.alg;
        let al = &sp.algs[a.alg];
        if al.base != al.close_indent + 2 {
            return Err(format!("spec.html:{}: steps not indented two past the emu-alg tag", al.line));
        }
        let vars = format!("#[{}]", a.vars.names.iter().map(|v| s(v)).collect::<Vec<_>>().join(", "));
        let at = if al.attrs.is_empty() { vec![] } else { crate::conv::parse_attrs(&format!(" {}", al.attrs))? };
        let doc = format!("/-- {} (§{}) -/", sp.clauses[a.clause].id, sp.clauses[a.clause].number);
        if d.sdo.is_some() {
            let prods = &a.prods;
            writeln!(
                o,
                "{doc}\ndef {} : SdoRow := {{\n  id := ⟨{}, {}⟩\n  sdo := {}\n  prods := {}\n  keys := {}\n  form := .alg {}\n  indent := {}\n  vars := {vars}\n  body := {}\n  closures := {}{} }}\n",
                guill(&d.name),
                cid(a.clause),
                a.idx,
                dt.decls.sdos.get(d.sdo.as_deref().unwrap()).ok_or("an SDO row's operation not interned")?,
                list(prods, |&p| pid(p).to_string()),
                list(&a.keys, |k| s(k)),
                attrs(&at),
                al.close_indent,
                nodes(&a.body),
                closures(&a.closures),
                if a.ext.is_some() { "\n  annex := true" } else { "" }
            )
            .unwrap();
            rows.push(guill(&d.name));
        } else {
            let header = header(&a.hdr);
            writeln!(
                o,
                "{doc}\ndef {} : Alg := {{\n  id := ⟨{}, {}⟩\n  name := {}\n  header := {header}\n  vars := {vars}\n  attrs := {}\n  indent := {}\n  body := {}\n  closures := {} }}\n",
                guill(&d.name),
                cid(a.clause),
                a.idx,
                s(&d.name),
                attrs(&at),
                al.close_indent,
                nodes(&a.body),
                closures(&a.closures)
            )
            .unwrap();
            algs.push(guill(&d.name));
        }
    }
    writeln!(o, "/-- The algorithms of this module, in document order. -/\ndef algs : List Alg := [{}]\n", algs.join(", ")).unwrap();
    writeln!(o, "/-- The SDO rows of this module, in document order. -/\ndef rows : List SdoRow := [{}]\n", rows.join(", ")).unwrap();
    writeln!(o, "end Ecma.Gen.{name}").unwrap();
    Ok(o)
}

pub(crate) fn piece(p: &Piece) -> String {
    match p {
        Piece::Word(w) => format!(".word {}", s(w)),
        Piece::Glue => ".glue".into(),
        Piece::Hole(k) => format!(
            ".hole {}",
            match k {
                HoleKind::E => 0,
                HoleKind::C => 1,
                HoleKind::T => 2,
                HoleKind::B => 3,
                HoleKind::S => 4,
                HoleKind::L => 5,
                HoleKind::Text => 6,
            }
        ),
        Piece::Choice(alts) => format!(".choice {}", list(alts, |a| list(a, piece))),
    }
}

/// The shard module of an overlay file (`sorts.emu`, or `sorts.emu, <clause>` for a sort): `Phrases_Sorts`.
pub fn phrase_shard(file: &str) -> String {
    let file = file.split(',').next().unwrap_or(file);
    let stem = file.rsplit('/').next().unwrap_or(file).trim_end_matches(".emu");
    let camel: String = stem.split(['-', '_']).map(|w| w[..1].to_uppercase() + &w[1..]).collect();
    format!("Phrases_{camel}")
}

/// The overlay's algorithms (phrase meanings, sort tests, operations) and row readings, each printing
/// back to its `<emu-alg>`: one module per overlay file (`phrase_shard`), and Ecma.Gen.Phrases joining them.
pub fn phrases(dt: &Data) -> Result<Vec<(String, String)>, String> {
    let mut shards: Vec<(String, Vec<String>, Vec<String>, String)> = Vec::new();
    let shard = |shards: &mut Vec<(String, Vec<String>, Vec<String>, String)>, file: &str| -> usize {
        let m = phrase_shard(file);
        match shards.iter().position(|x| x.0 == m) {
            Some(i) => i,
            None => {
                shards.push((m, vec![], vec![], String::new()));
                shards.len() - 1
            }
        }
    };
    for pa in &dt.phrase_algs {
        let m = Some(crate::decls::Meaning::Alg(pa.clause));
        let op = !dt.decls.ops[pa.clause].is_empty();
        if !op && !dt.decls.phrases.iter().any(|x| x.meaning == m) && !dt.decls.sort_defs.iter().flatten().any(|x| x.test == m) {
            return Err(format!("{}: no phrase row or sort has this algorithm as its meaning, and it is no operation", pa.id));
        }
        if let Some((t, why)) = pa.exceptions.first() {
            return Err(format!("{}: a step without a data shape: {t} ({why})", pa.id));
        }
        if crate::print::body(&dt.decls, &pa.vars.names, &pa.closures, &pa.body, pa.alg.base, pa.alg.close_indent) != pa.alg.raw {
            return Err(format!("{}: the algorithm does not print back", pa.id));
        }
        if pa.alg.base != pa.alg.close_indent + 2 {
            return Err(format!("{}: steps not indented two past the emu-alg tag", pa.id));
        }
        let vars = format!("#[{}]", pa.vars.names.iter().map(|v| s(v)).collect::<Vec<_>>().join(", "));
        let i = shard(&mut shards, &pa.file);
        writeln!(
            shards[i].3,
            "/-- {} ({}) -/\ndef {} : Alg := {{\n  id := ⟨{}, 0⟩\n  name := {}\n  header := {}\n  vars := {vars}\n  attrs := []\n  indent := {}\n  body := {}\n  closures := {} }}\n",
            pa.id,
            pa.file,
            guill(&pa.id),
            pa.clause,
            s(&pa.id),
            header(&pa.hdr),
            pa.alg.close_indent,
            nodes(&pa.body),
            closures(&pa.closures)
        )
        .unwrap();
        shards[i].1.push(guill(&pa.id));
    }
    if let Some(e) = dt.row_errors.first() {
        return Err(e.clone());
    }
    if !dt.name_clashes.is_empty() {
        return Err(format!("primitives named as an operation or a concrete method: {}", dt.name_clashes.join(", ")));
    }
    for r in &dt.reading_rows {
        if let Some((t, why)) = r.exceptions.first() {
            return Err(format!("{}: a step without a data shape: {t} ({why})", r.id));
        }
        if crate::print::body(&dt.decls, &r.vars.names, &r.closures, r.steps(), r.alg.base, r.alg.close_indent) != r.alg.raw {
            return Err(format!("{}: the row does not print back", r.id));
        }
        if r.alg.base != r.alg.close_indent + 2 {
            return Err(format!("{}: steps not indented two past the emu-alg tag", r.id));
        }
        let vars = format!("#[{}]", r.vars.names.iter().map(|v| s(v)).collect::<Vec<_>>().join(", "));
        // an erratum's row: its emu-alg is the `test262 proposed` reading
        let form = match r.erratum {
            Some(_) => vec![Attr { key: "reading".into(), value: Some("test262 proposed".into()) }],
            None => vec![],
        };
        let i = shard(&mut shards, &r.file);
        writeln!(
            shards[i].3,
            "/-- {} ({}) -/\ndef {} : SdoRow := {{\n  id := ⟨{}, 0⟩\n  sdo := {}\n  prods := {}\n  keys := {}\n  form := .alg {}\n  indent := {}\n  vars := {vars}\n  body := {}\n  closures := {}{} }}\n",
            r.id,
            r.file,
            guill(&r.id),
            r.clause,
            dt.decls.sdos.get(&r.sdo).ok_or("a row reading's operation not interned")?,
            list(&r.prods, |&p| pid(p).to_string()),
            list(&r.keys, |k| s(k)),
            attrs(&form),
            r.alg.close_indent,
            nodes(&r.body),
            closures(&r.closures),
            if r.annex { "\n  annex := true" } else { "" }
        )
        .unwrap();
        shards[i].2.push(guill(&r.id));
    }
    let mut out = Vec::new();
    for (m, algs, rows, body) in &shards {
        let mut o = String::new();
        writeln!(o, "module\n\npublic import Ecma.Notation.Syntax\n\n/-! {HEADER} -/\n\n@[expose] public section\n\nnamespace Ecma.Gen.{m}\n\nopen Ecma\n").unwrap();
        o.push_str(body);
        writeln!(o, "/-- The algorithms of this module, in the overlay's order. -/\ndef algs : List Alg := [{}]\n", algs.join(", ")).unwrap();
        writeln!(o, "/-- The SDO rows the overlay's readings add. -/\ndef rows : List SdoRow := [{}]\n", rows.join(", ")).unwrap();
        writeln!(o, "end Ecma.Gen.{m}").unwrap();
        out.push((m.clone(), o));
    }
    let mut o = String::new();
    writeln!(o, "module\n").unwrap();
    for (m, ..) in &shards {
        writeln!(o, "public import Ecma.Gen.{m}").unwrap();
    }
    writeln!(o, "\n/-! {HEADER} -/\n\n@[expose] public section\n\nnamespace Ecma.Gen.Phrases\n\nopen Ecma\n").unwrap();
    let cat = |f: &str| shards.iter().map(|x| format!("{}.{f}", x.0)).collect::<Vec<_>>().join(" ++ ");
    writeln!(o, "/-- The overlay's algorithms, by file in the overlay's order. -/\ndef algs : List Alg := {}\n", cat("algs")).unwrap();
    writeln!(o, "/-- The SDO rows the overlay's readings add. -/\ndef rows : List SdoRow := {}\n", cat("rows")).unwrap();
    writeln!(o, "end Ecma.Gen.Phrases").unwrap();
    out.push(("Phrases".to_string(), o));
    Ok(out)
}

pub(crate) fn meaning(m: &Option<crate::decls::Meaning>) -> String {
    use crate::decls::{Meaning, PArg};
    match m {
        None => ".none".into(),
        Some(Meaning::Alg(c)) => format!("(.alg ⟨{c}, 0⟩)"),
        Some(Meaning::Prim { prim, args, neg }) => format!(
            "(.prim {} {} {})",
            prim,
            list(args, |a| match a {
                PArg::Hole(i) => format!(".hole {i}"),
                PArg::Spread(i) => format!("(.spread {i})"),
                PArg::Enum(e) => format!(".enum {e}"),
                PArg::Subject => ".subject".into(),
                PArg::ThisNode => ".thisNode".into(),
                PArg::Sort(k) => format!("(.sort {k})"),
                PArg::Field(f) => format!("(.field {f})"),
                PArg::Choice(k) => format!("(.choice {k})"),
            }),
            b(*neg)
        ),
    }
}

/// The phrase category number of a grammar category.
pub(crate) fn phrase_cat(c: &str) -> usize {
    match c {
        "Step" => 0,
        "P" | "GP" => 1,
        "CA" => 2,
        "PRED" => 3,
        "T" => 4,
        "ER" => 0,
        _ => 5,
    }
}

/// An array literal, in chunks of at most 200 elements joined by `++`
/// (one long literal exceeds the elaborator's recursion depth).
pub(crate) fn array(xs: Vec<String>) -> String {
    if xs.is_empty() {
        return "#[]".into();
    }
    xs.chunks(200).map(|c| format!("#[{}]", c.join(", "))).collect::<Vec<_>>().join(" ++
    ")
}

fn names(t: &crate::decls::Table) -> String {
    array(t.names.iter().map(|x| s(x)).collect())
}

/// Each primitive's signature and meaning: the overlay's declaration, else the residue
/// classifier's, else empty (a notation primitive the machine defines).
fn prim_docs(dt: &Data) -> String {
    let d = &dt.decls;
    array(
        d.prims
            .names
            .iter()
            .map(|n| {
                let (sig, m) = match (dt.overlay_docs.iter().find(|x| &x.0 == n), crate::residue::PRIMS.iter().find(|p| p.name == n)) {
                    (Some((_, sig, m)), _) => (sig.clone(), m.clone()),
                    (None, Some(p)) => (p.sig.to_string(), p.meaning.to_string()),
                    _ => (String::new(), String::new()),
                };
                format!("{{ sig := {}, meaning := {} }}", s(&sig), s(&m))
            })
            .collect(),
    )
}

/// Each nonterminal whose one main-grammar rule has only right-hand sides of one terminal, with
/// those terminals in grammar order.
fn grammar_alts(dt: &Data) -> String {
    use jsgrammar::grammar::{Body, Item, Sym, Terminal};
    let gl = &dt.env.gl;
    let mut rules: BTreeMap<&str, Vec<&jsgrammar::grammar::Rule>> = BTreeMap::new();
    for b in gl.blocks.iter().filter(|b| b.g != jsgrammar::gl::G::AnnexB && matches!(b.prose, jsgrammar::spec::Prose::Main)) {
        for r in &b.rules {
            rules.entry(r.lhs.as_str()).or_default().push(r);
        }
    }
    let term = |t: &Terminal| match t {
        Terminal::Text(x, _) => format!(".text {}", s(x)),
        Terminal::Cp(n) => format!(".cp {}", s(n)),
    };
    let mut out = Vec::new();
    for (lhs, rs) in rules {
        let ([r], Some(k)) = (rs.as_slice(), dt.decls.nts.get(lhs)) else { continue };
        let ts: Option<Vec<&Terminal>> = match &r.body {
            Body::OneOf(rows) => Some(rows.iter().flatten().collect()),
            Body::Alts(alts) => alts
                .iter()
                .map(|a| match a.rhs.as_slice() {
                    [Item::Sym(Sym::T(t), false)] if a.guard.is_empty() => Some(t),
                    _ => None,
                })
                .collect(),
        };
        if let Some(ts) = ts {
            out.push((k, format!("({k}, {})", list(&ts, |t| term(t)))));
        }
    }
    out.sort();
    array(out.into_iter().map(|x| x.1).collect())
}

/// Per clause a production-in phrase names, the productions its grammar blocks define (an Annex B
/// overlay's included), and those of an Annex B overlay of a grammar whose main blocks all lie in it.
fn clause_prods(dt: &Data) -> String {
    use jsgrammar::gl::G;
    use jsgrammar::spec::Prose;
    let gl = &dt.env.gl;
    let lines = gl.prod_lines();
    let mut out = Vec::new();
    for &c in &dt.decls.prod_clauses {
        let name = &dt.decls.clauses.names[c];
        let whole = |g: G| {
            let mut bs = gl.blocks.iter().filter(|b| b.g == g && matches!(b.prose, Prose::Main)).peekable();
            bs.peek().is_some() && bs.all(|b| gl.within(&b.clause, name))
        };
        let ids: Vec<usize> = gl
            .prods
            .iter()
            .enumerate()
            .filter(|(_, p)| {
                let bl = &gl.blocks[p.at.block];
                match &bl.prose {
                    Prose::Overlay { section, .. } => {
                        gl.within(&bl.clause, name)
                            || whole(match *section {
                                "regExpPatterns" => G::RegExp,
                                "htmlLikeComments" => G::Lexical,
                                _ => G::Syntactic,
                            })
                    }
                    _ => gl.within(&bl.clause, name),
                }
            })
            .filter_map(|(i, _)| dt.decls.prods.get(lines[i].split_once(' ').map_or(&lines[i][..], |x| x.1)))
            .collect();
        out.push(format!("({c}, {})", list(&ids, |i| i.to_string())));
    }
    array(out)
}

/// The declarations module.
pub fn decls(dt: &Data) -> String {
    let d = &dt.decls;
    let mut o = String::new();
    writeln!(o, "module\n\npublic import Ecma.Notation.Syntax\n\n/-! {HEADER} -/\n\n@[expose] public section\n\nnamespace Ecma.Gen\n\nopen Ecma\n").unwrap();
    let phrases = array(
        d.phrases.iter().map(|p| format!("{{ cat := {}, template := {}, meaning := {} }}", phrase_cat(p.cat), list(&p.template, piece), meaning(&p.meaning))).collect(),
    );
    let sdo_headers = array(dt.sdo_headers.iter().map(|h| opt(h, header)).collect());
    let sort_defs = array(
        (0..d.sorts.names.len())
            .map(|k| match d.sort_defs.get(k).cloned().flatten() {
                None if k < crate::data::SORTS.len() => "none".to_string(),
                None => "some {}".to_string(),
                Some(x) => format!(
                    "some {{ super := {}, test := {}, record := {}{} }}",
                    list(&x.sup, |k| k.to_string()),
                    meaning(&x.test),
                    b(x.record),
                    x.ctx.map(|p| format!(", context := some {p}")).unwrap_or_default()
                ),
            })
            .collect(),
    );
    // the errata by id: an id the overlay no longer has keeps its name, with no overlay id
    let (errata, parity, errata_ids) = {
        let n = d.errata_table.names.len().max(d.errata.len());
        let mut at: Vec<Option<usize>> = vec![None; n];
        for e in 0..d.errata.len() {
            at[eid(e)] = Some(e);
        }
        let name = |k: usize| at[k].map_or_else(|| d.errata_table.names.get(k).cloned().unwrap_or_default(), |e| d.errata[e].clone());
        (
            array((0..n).map(|k| s(&name(k))).collect()),
            array((0..n).map(|k| at[k].map_or(".literal", |e| reading(d.parity[e])).to_string()).collect()),
            array((0..n).map(|k| s(at[k].map_or("", |e| d.errata_ids[e].as_str()))).collect()),
        )
    };
    let tables: [(&str, &str, String); 23] = [
        ("clauses", "clause ids, by `ClauseId` (spec/formal/clause-ids.txt: a clause the text no longer has keeps its number and its name)", names(&d.clauses)),
        ("ops", "per clause, the operation it defines", array(d.ops.iter().map(|x| s(x)).collect())),
        ("fields", "fields, slots, methods, components and intrinsics", names(&d.fields)),
        ("enums", "enum constants", names(&d.enums)),
        ("sdos", "syntax-directed operations", names(&d.sdos)),
        ("nts", "nonterminals", names(&d.nts)),
        ("params", "grammatical parameters", names(&d.params)),
        ("prods", "productions", names(&d.prods)),
        ("prims", "primitives", names(&d.prims)),
        ("sorts", "sort names and modifiers", names(&d.sorts)),
        ("methods", "concrete-method names", names(&d.methods)),
        ("sortDefs", "sorts' definitions, by sort: none for a Known sort the overlay does not define, residue for a sort with none", sort_defs),
        ("phrases", "the phrase table", phrases),
        ("sdoHeaders", "SDOs' headers, by SDO", sdo_headers),
        (
            "sdoDefaults",
            "SDOs' implicit default definitions, by SDO",
            array((0..d.sdos.names.len()).map(|k| opt(&d.sdo_defaults.iter().find(|x| x.0 == k).map(|x| (x.1, x.2)), |(c, i)| format!("⟨{c}, {i}⟩"))).collect()),
        ),
        ("primDocs", "primitives' signatures and meanings, by primitive", prim_docs(dt)),
        ("reasons", "residue channel (a)'s spec-issue reasons", names(&d.reasons)),
        ("notes", "residue channel (c)'s kinds", names(&d.notes)),
        ("errata", "errata and definition readings, by `ErratumId` (spec/formal/erratum-ids.txt: a retired one keeps its number and its name)", errata),
        ("parity", "per erratum, the reading today's model applies (`.literal` for a retired one)", parity),
        ("alts", "nonterminals whose right-hand sides are each one terminal, with those terminals", grammar_alts(dt)),
        ("clauseProds", "productions defined in the clauses a production-in phrase names", clause_prods(dt)),
        (
            "jobErrata",
            "literal errata whose text stops at the job loop's check for a Job the clause makes",
            array(d.job_errata.iter().map(|(c, e)| format!("({c}, {})", eid(*e))).collect()),
        ),
    ];
    for (n, doc, v) in &tables {
        let t = match *n {
            "phrases" => "Array Phrase",
            "sdoHeaders" => "Array (Option Header)",
            "sdoDefaults" => "Array (Option AlgId)",
            "parity" => "Array Reading",
            "primDocs" => "Array PrimDoc",
            "sortDefs" => "Array (Option SortDef)",
            "alts" => "Array (NtId × List GTerminal)",
            "clauseProds" => "Array (ClauseId × List ProdId)",
            "jobErrata" => "Array (ClauseId × ErratumId)",
            _ => "Array String",
        };
        // the phrase table's chunks as definitions of their own: one definition of them all
        // exceeds the compiler's recursion depth
        let parts: Vec<&str> = v.split(" ++\n    ").collect();
        if *n == "phrases" && parts.len() > 1 {
            for (k, c) in parts.iter().enumerate() {
                writeln!(o, "/-- The {doc}, part {k}. -/\ndef {n}{k} : {t} :=\n    {c}\n").unwrap();
            }
            let all = (0..parts.len()).map(|k| format!("{n}{k}")).collect::<Vec<_>>().join(" ++ ");
            writeln!(o, "/-- The {doc}. -/\ndef {n} : {t} :=\n    {all}\n").unwrap();
            continue;
        }
        writeln!(o, "/-- The {doc}. -/\ndef {n} : {t} :=\n    {v}\n").unwrap();
    }
    writeln!(o, "/-- The errata's overlay ids, by `ErratumId` (`\"\"` for a retired one). -/\ndef errataIds : Array String :=\n    {}\n", errata_ids).unwrap();
    let erratum_readings = {
        let n = d.errata_table.names.len().max(d.errata.len());
        let mut at: Vec<Option<usize>> = vec![None; n];
        for e in 0..d.errata.len() {
            at[eid(e)] = Some(e);
        }
        array((0..n).map(|k| at[k].map_or("[]".to_string(), |e| {
            let rs: Vec<_> = d.erratum_readings[e].iter().map(|r| reading(*r)).collect();
            format!("[{}]", rs.join(", "))
        })).collect())
    };
    writeln!(o, "/-- Per `ErratumId`, the readings its overlay or parser defines (empty for a definition reading or retired id). -/\ndef erratumReadings : Array (List Reading) :=\n    {erratum_readings}\n").unwrap();
    let stops = array(d.erratum_stops.iter().map(|(e, c, p, k)| format!("({}, {}, {}, {})", eid(*e), s(c), s(p), opt(k, |k| s(k)))).collect());
    writeln!(o, "/-- Where the literal errata stop a run (`stops=` in readings.emu): erratum, clause id, step path (`-`:\noutside any step, the job loop's check of §9.5), the innermost caller's clause id if the stop is only\nunder it. -/\ndef erratumStops : Array (ErratumId × String × String × Option String) :=\n    {stops}\n").unwrap();
    let perm = array(d.permanent.iter().map(|(c, p, k)| format!("({}, {}, {})", s(c), s(p), s(k))).collect());
    writeln!(o, "/-- The residue steps given no meaning on purpose (`<emu-permanent>`): clause (`sec-x`, `sec-x#n`) or\noverlay id, step, class. -/\ndef permanentSteps : Array (String × String × String) :=\n    {perm}\n").unwrap();
    let fields = tables.iter().map(|(n, _, _)| format!("{n} := {n}")).collect::<Vec<_>>().join(", ");
    writeln!(o, "/-- The declaration tables. -/\ndef decls : Decls := {{ {fields} }}\n\nend Ecma.Gen").unwrap();
    o
}

/// The index module: every data module's algorithms and SDO rows, in order.
pub fn index(mods: &[String]) -> String {
    let mut o = String::new();
    writeln!(o, "module\n").unwrap();
    for m in mods {
        writeln!(o, "public import Ecma.Gen.{m}").unwrap();
    }
    writeln!(o, "\n/-! {HEADER} -/\n\n@[expose] public section\n\nnamespace Ecma.Gen\n\nopen Ecma\n").unwrap();
    let cat = |f: &str| mods.iter().map(|m| format!("{m}.{f}")).collect::<Vec<_>>();
    writeln!(o, "/-- Every algorithm, by module. -/\ndef algs : List (List Alg) := [\n    {}]\n", cat("algs").join(",\n    ")).unwrap();
    writeln!(o, "/-- Every SDO row, by module. -/\ndef rows : List (List SdoRow) := [\n    {}]\n", cat("rows").join(",\n    ")).unwrap();
    writeln!(o, "end Ecma.Gen").unwrap();
    o
}
