//! The data as Lean modules (`Ecma.Gen.*`): constructor, `List` and
//! `#[…]` terms of `Ecma.Notation.Syntax` only. One module per clause group,
//! sharded at `SHARD_STEPS` steps; the declarations in `Ecma.Gen.Decls`.

use crate::ast::*;
