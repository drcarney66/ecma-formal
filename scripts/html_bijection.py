#!/usr/bin/env python3
"""The bijection between `spec/spectec/**/*.spectec` (+ `spec/html/`) and `spec.html`'s
autogenerated algorithms, SDO equations, Early Error rules, grammar keys, and
definition grammars.

    python3 scripts/html_bijection.py [--spec PATH] [--bin target/release/spectec-html]
                                      [--json FILE] [-v]
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

import spec_text

ROOT = Path(os.path.abspath(__file__)).parent.parent


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bin", dest="binary", default=str(ROOT / "target/release/spectec-html"))
    ap.add_argument("--spec-dir", default=str(ROOT / "spec/spectec"))
    ap.add_argument("--meta-dir", default=str(ROOT / "spec/html"))
    ap.add_argument("--spec", help="a spec.html or its directory (default: scripts/spec_text.py)")
    ap.add_argument("--json", metavar="FILE", help="write machine-readable summary JSON")
    ap.add_argument("-v", action="store_true", help="print full spectec-html check output")
    a = ap.parse_args()

    binary = Path(a.binary)
    if not binary.is_file():
        print(f"FAIL html bijection: {binary} not found (run `cargo build --release -p spectec-html`)")
        return 1

    html_path = spec_text.resolve(a.spec)
    cmd = [
        str(binary),
        f"--spec-dir={a.spec_dir}",
        f"--meta-dir={a.meta_dir}",
        f"--spec={html_path}",
        "check",
    ]
    if a.json:
        cmd.append(f"--json={a.json}")

    proc = subprocess.run(cmd, capture_output=True, text=True)
    out = (proc.stdout + proc.stderr).strip()
    if a.v or proc.returncode != 0:
        if out:
            print(out)
    else:
        for ln in out.splitlines():
            print(ln)
    return proc.returncode


if __name__ == "__main__":
    sys.exit(main())
