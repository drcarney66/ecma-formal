#!/usr/bin/env python3
"""Generate all derived Lean modules and parser index from `spec/spectec/` and Unicode inputs.

    nix develop ~/.local/state/ecma-formal/devshell -c python3 scripts/generate.py [--force]

Every `Gen/` directory under `lean/` (`lean/Unicode/Gen`, `lean/Ecma/Unicode/Gen`,
`lean/Ecma/Grammar/Gen`, `lean/Ecma/Gen`) and `tests/parser/grammar_index.txt` are gitignored
and produced here before `lake build`:

1. Builds `target/release/spectec` if missing or older than `crates/spectec/`.
2. Generates `lean/Unicode/Gen/*.lean` (`unicode_properties.py`, `unicode_data.py`), cached by input stamp.
3. Resolves `spec_text.spec_dir()` and generates `lean/Ecma/Unicode/Gen/Properties.lean` (`ecma_unicode_properties.py`).
4. Runs `spectec --spec-dir=spec/spectec emit --lean-dir=lean --grammar-index=tests/parser/grammar_index.txt`.

Files whose generated bytes are unchanged keep their mtimes so `lake build` stays incremental.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import spec_text  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SPEC_DIR = ROOT / "spec/spectec"
UNICODE_GEN = ROOT / "lean/Unicode/Gen"
UNICODE_STAMP = ROOT / "build/unicode-gen.stamp"


def ensure_spectec() -> Path:
    spectec = ROOT / "target/release/spectec"
    rs_files = [
        *((ROOT / "crates/spectec").rglob("*.rs")),
        ROOT / "crates/spectec/Cargo.toml",
    ]
    newest_src = max(f.stat().st_mtime for f in rs_files if f.exists())
    if not spectec.exists() or spectec.stat().st_mtime < newest_src:
        print("+ cargo build --release --bin spectec", flush=True)
        subprocess.run(["cargo", "build", "--release", "--bin", "spectec"], cwd=ROOT, check=True)
    return spectec


def unicode_digest() -> str:
    ucd = os.environ.get("UNICODE_UCD", "")
    h = hashlib.sha256(ucd.encode())
    for s in ("scripts/unicode_properties.py", "scripts/unicode_data.py"):
        h.update((ROOT / s).read_bytes())
    return h.hexdigest()


def ensure_unicode(force: bool) -> None:
    want = unicode_digest()
    expected = [
        UNICODE_GEN / n
        for n in (
            "CaseData.lean",
            "NormalizationData.lean",
            "GeneralCategory.lean",
            "Scripts.lean",
            "BinaryProperties1.lean",
            "BinaryProperties2.lean",
            "BinaryProperties3.lean",
            "EmojiSequences.lean",
            "Classes.lean",
            "PropertyValues.lean",
            "PropertyValueAliases.lean",
        )
    ]
    if not force and UNICODE_STAMP.exists() and UNICODE_STAMP.read_text().strip() == want and all(p.exists() for p in expected):
        return
    print("+ generating lean/Unicode/Gen", flush=True)
    subprocess.run([sys.executable, str(ROOT / "scripts/unicode_properties.py")], cwd=ROOT, check=True)
    subprocess.run([sys.executable, str(ROOT / "scripts/unicode_data.py")], cwd=ROOT, check=True)
    UNICODE_STAMP.parent.mkdir(parents=True, exist_ok=True)
    UNICODE_STAMP.write_text(want + "\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true", help="regenerate Unicode tables even when stamp matches")
    a = ap.parse_args()

    spectec = ensure_spectec()
    ensure_unicode(a.force)

    sdir = spec_text.spec_dir()
    subprocess.run([sys.executable, str(ROOT / "scripts/ecma_unicode_properties.py"), "--spec", str(sdir)], cwd=ROOT, check=True)

    subprocess.run(
        [
            str(spectec),
            f"--spec-dir={SPEC_DIR}",
            "emit",
            f"--lean-dir={ROOT / 'lean'}",
            f"--grammar-index={ROOT / 'tests/parser/grammar_index.txt'}",
        ],
        cwd=ROOT,
        check=True,
    )
    print(f"generated all Gen/ modules and parser index from {SPEC_DIR.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
