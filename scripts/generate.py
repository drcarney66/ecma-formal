#!/usr/bin/env python3
"""Generate all derived Lean modules, active ID tables, and formal report files.

    nix develop ~/.local/state/ecma-formal/devshell -c python3 scripts/generate.py [--force] [--update-base-ids]

Every `Gen/` directory under `lean/` (`lean/Unicode/Gen`, `lean/Ecma/Unicode/Gen`, `lean/Ecma/Grammar/Gen`,
`lean/Ecma/Gen`) and the derived snapshot files (`spec/formal/{assert-sites,permanent-sentences,errata,type-dyn-sites}.txt`,
`tests/parser/grammar_index.txt`) are gitignored and produced here before `lake build`:

1. Builds `target/release/spec-gen` and `target/release/jsgrammar` if missing or older than `crates/`.
2. Generates `lean/Unicode/Gen/*.lean` (`unicode_properties.py`, `unicode_data.py`), cached by input stamp.
3. Resolves `spec_text.spec_dir()` (merging `spec/proposals.txt` if any) and generates
   `lean/Ecma/Unicode/Gen/Properties.lean` (`ecma_unicode_properties.py`).
4. Seeds `build/ids/*-ids.txt` from the base `spec/formal/*-ids.txt` tables so base IDs never shift and
   proposal branches leave `spec/formal/*-ids.txt` untouched (`--update-base-ids` writes back to `spec/formal/`).
5. Runs `jsgrammar.py --write --ids build/ids` -> `lean/Ecma/Grammar/Gen/*.lean` + `tests/parser/grammar_index.txt`.
6. Runs `gen_spec.py --write --ids build/ids` -> `lean/Ecma/Gen/*.lean` + the derived `spec/formal/*.txt` reports.

Files whose generated bytes are unchanged keep their mtimes so `lake build` stays incremental.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import spec_text  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
FORMAL = ROOT / "spec/formal"
IDS_OUT = spec_text.IDS_OUT
UNICODE_GEN = ROOT / "lean/Unicode/Gen"
ECMA_UNICODE_GEN = ROOT / "lean/Ecma/Unicode/Gen"
UNICODE_STAMP = ROOT / "build/unicode-gen.stamp"


def write_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    data = content.encode("utf-8")
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def ensure_rust_generators() -> tuple[Path, Path]:
    spec_gen = ROOT / "target/release/spec-gen"
    jsg = ROOT / "target/release/jsgrammar"
    rs_files = [*((ROOT / "crates/jsgrammar").rglob("*.rs")), *((ROOT / "crates/spec-gen").rglob("*.rs")),
                ROOT / "crates/jsgrammar/Cargo.toml", ROOT / "crates/spec-gen/Cargo.toml"]
    newest_src = max(f.stat().st_mtime for f in rs_files if f.exists())
    if any(not b.exists() or b.stat().st_mtime < newest_src for b in (spec_gen, jsg)):
        print("+ cargo build --release --bin spec-gen --bin jsgrammar", flush=True)
        subprocess.run(["cargo", "build", "--release", "--bin", "spec-gen", "--bin", "jsgrammar"], cwd=ROOT, check=True)
    return spec_gen, jsg


def unicode_digest() -> str:
    ucd = os.environ.get("UNICODE_UCD", "")
    h = hashlib.sha256(ucd.encode())
    for s in ("scripts/unicode_properties.py", "scripts/unicode_data.py"):
        h.update((ROOT / s).read_bytes())
    return h.hexdigest()


def ensure_unicode(force: bool) -> None:
    want = unicode_digest()
    expected = [UNICODE_GEN / n for n in (
        "CaseData.lean", "NormalizationData.lean", "GeneralCategory.lean", "Scripts.lean",
        "BinaryProperties1.lean", "BinaryProperties2.lean", "BinaryProperties3.lean",
        "EmojiSequences.lean", "Classes.lean", "PropertyValues.lean", "PropertyValueAliases.lean",
    )]
    if not force and UNICODE_STAMP.exists() and UNICODE_STAMP.read_text().strip() == want and all(p.exists() for p in expected):
        return
    print("+ generating lean/Unicode/Gen", flush=True)
    subprocess.run([sys.executable, str(ROOT / "scripts/unicode_properties.py")], cwd=ROOT, check=True)
    subprocess.run([sys.executable, str(ROOT / "scripts/unicode_data.py")], cwd=ROOT, check=True)
    UNICODE_STAMP.parent.mkdir(parents=True, exist_ok=True)
    UNICODE_STAMP.write_text(want + "\n")


def seed_ids(target: Path) -> None:
    """Seed `target` from `spec/formal/*-ids.txt`, pre-appending any new `<emu-erratum name=...>` in `spec/formal/*.emu`."""
    target.mkdir(parents=True, exist_ok=True)
    for src in sorted(FORMAL.glob("*-ids.txt")):
        shutil.copyfile(src, target / src.name)
    err_path = target / "erratum-ids.txt"
    if err_path.exists():
        lines = err_path.read_text().splitlines()
        known: dict[str, int] = {}
        max_id = -1
        for l in lines:
            if l and not l.startswith("#"):
                parts = l.split("\t")
                idx = int(parts[0])
                known[parts[1]] = idx
                max_id = max(max_id, idx)
        added = []
        for emu in sorted(FORMAL.glob("*.emu")):
            for m in re.finditer(r'<emu-erratum\b[^>]*\bname="([^"]+)"', emu.read_text()):
                name = m.group(1)
                if name not in known:
                    max_id += 1
                    known[name] = max_id
                    added.append(f"{max_id}\t{name}")
        if added:
            err_path.write_text("\n".join(lines + added) + "\n")


def generate_reports(spec_gen: Path, jsg: Path, spec_html: Path, ids_dir: Path) -> None:
    ov = f"--overlay={FORMAL}"
    ids_arg = f"--ids={ids_dir}"
    sp_arg = f"--spec={spec_html}"

    for cmd, sub, dst in (
        ("asserts", ["-all"], FORMAL / "assert-sites.txt"),
        ("residue", ["-permanent"], FORMAL / "permanent-sentences.txt"),
        ("errata", [], FORMAL / "errata.txt"),
        ("types", ["-dyn"], FORMAL / "type-dyn-sites.txt"),
    ):
        r = subprocess.run([str(spec_gen), sp_arg, ov, ids_arg, cmd, *sub], cwd=ROOT, capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f"generate.py: spec-gen {cmd} {' '.join(sub)} failed:\n{r.stderr}")
        write_if_changed(dst, r.stdout)

    r = subprocess.run(
        [str(jsg), "--spec", str(spec_html), "--prods", "--ids", str(ids_dir), "--json", str(FORMAL / "json.emu")],
        cwd=ROOT, capture_output=True, text=True,
    )
    if r.returncode != 0:
        sys.exit(f"generate.py: jsgrammar --prods failed:\n{r.stderr}")
    write_if_changed(ROOT / "tests/parser/grammar_index.txt", "# Generated by scripts/generate.py (jsgrammar --prods)\n" + r.stdout)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true", help="regenerate Unicode tables even when stamp matches")
    ap.add_argument("--update-base-ids", action="store_true", help="copy updated *-ids.txt back into spec/formal/")
    a = ap.parse_args()

    spec_gen, jsg = ensure_rust_generators()
    ensure_unicode(a.force)

    sdir = spec_text.spec_dir()
    shtml = sdir / "spec.html"
    subprocess.run([sys.executable, str(ROOT / "scripts/ecma_unicode_properties.py"), "--spec", str(sdir)], cwd=ROOT, check=True)

    ids_dir = FORMAL if a.update_base_ids else IDS_OUT
    if not a.update_base_ids:
        seed_ids(IDS_OUT)

    subprocess.run([
        sys.executable, str(ROOT / "scripts/jsgrammar.py"), "--write",
        "--gen", str(jsg), "--spec", str(shtml), "--ids", str(ids_dir),
        "--readings", str(FORMAL / "readings.emu"),
        "--readings", str(FORMAL / "syntax.emu"),
        "--json", str(FORMAL / "json.emu"),
    ], cwd=ROOT, check=True)

    subprocess.run([
        sys.executable, str(ROOT / "scripts/gen_spec.py"), "--write",
        "--gen", str(spec_gen), "--spec", str(shtml), "--ids", str(ids_dir),
    ], cwd=ROOT, check=True)

    generate_reports(spec_gen, jsg, shtml, ids_dir)
    print(f"generated all Gen/ modules, reports, and ids ({ids_dir.relative_to(ROOT)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
